package app.askya.data.entity

import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey
import app.askya.domain.model.AccountKind
import app.askya.domain.model.EntryKind
import app.askya.domain.model.MarkColor
import java.time.LocalDate
import java.time.LocalDateTime

/**
 * Счёт — место, где деньги лежат: кошелёк, карта, копилка, долг.
 *
 * Остаток в самой строке не хранится, и это главное решение всей книги.
 * Хранится только [opening] — сколько было в тот день, когда счёт завели, — а
 * нынешний остаток каждый раз складывается из записей. Иначе у одного и того
 * же числа появилось бы два источника правды: колонка «остаток» и лента
 * записей, — и первая же правка задним числом («вчерашняя трата была не 500, а
 * 700») развела бы их навсегда. Складывать записи заново дёшево: их сотни, а
 * не миллионы, и складывает их SQL.
 *
 * Закрытый счёт ([closed]) не удаляется: на нём висит история, и стереть его
 * значило бы стереть прошлогодний месяц. Он просто перестаёт предлагаться в
 * записи и уходит вниз списка.
 */
@Entity(tableName = "ledger_accounts")
data class LedgerAccount(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val title: String = "",
    val kind: AccountKind = AccountKind.CARD,
    /** Сколько было на счету, когда его завели. Может быть и отрицательным — долг. */
    val opening: Long = 0,
    /**
     * Кредитный лимит в копейках — потолок, до которого банк даёт занимать.
     * 0 означает «лимита нет», а не «занимать нельзя»: у всех прочих видов
     * счёта его нет вовсе, и заводить ради этого отдельный флаг незачем.
     *
     * Колонкой у счёта, а не отдельной таблицей «кредиты»: это одно число,
     * и живёт оно ровно столько же, сколько сам счёт.
     */
    val limit: Long = 0,
    /**
     * Ставка по долгу в сотых долях процента годовых: 24,9 % — это 2490.
     *
     * Сотыми, а не дробью: ставку пишут с одним знаком после запятой, а
     * `Double` в книге не живёт по той же причине, что и в суммах, — см.
     * [app.askya.domain.model.formatMoney]. 0 значит «процентов нет», и это
     * не отговорка: по долгу другу их и правда нет, а у карты с беспроцентным
     * периодом их нет ровно до тех пор, пока в него укладываются.
     *
     * Нужна она одному — плану погашения: без ставки план считает, сколько
     * платить, но не считает, сколько сверху отдадите банку.
     */
    val rate: Int = 0,
    /** Краска-метка. Пусто — выводится из названия, см. [MarkColor]. */
    val color: MarkColor? = null,
    val closed: Boolean = false,
    /**
     * Место счёта в сетке — тот порядок, в каком человек их сам разложил.
     *
     * Не по дате появления и не по остатку: счетов пять-шесть, смотрят на них
     * каждый день, и первым человек хочет видеть тот, которым платит, а не тот,
     * который завёл раньше всех. Сортировать по остатку было бы ещё хуже —
     * карточки менялись бы местами после каждой покупки хлеба, и глаз перестал
     * бы находить свою карту не читая.
     *
     * Порядок общий на все счета, а закрытые уходят вниз запросом
     * ([app.askya.data.db.dao.LedgerDao.observeAccounts]): закрытый счёт своё
     * место в списке не занимает, но и не теряет — открой его снова, и он
     * вернётся, куда его клали.
     */
    val position: Int = 0,
    val createdAt: LocalDateTime = LocalDateTime.now(),
)

/**
 * Статья — на что тратят и откуда получают: «Еда», «Дом», «Зарплата».
 *
 * У статьи есть вид ([kind]), и он всегда либо расход, либо доход: статья
 * «на всё» была бы графой, в которой еда складывается с зарплатой. Переводу
 * статья не нужна вовсе — он ничего не тратит и ничего не приносит.
 *
 * [limit] — предел на месяц, и это весь бюджет, какой здесь есть. Не план по
 * месяцам вперёд, не остаток «на день», не перенос неистраченного: одна
 * строчка «больше этого в месяц не хочу» и полоска, которая показывает, сколько
 * от неё осталось. Ноль означает «предела нет», а не «нельзя тратить»: статья
 * без предела — обычное дело, и хранить для неё отдельный флаг незачем.
 */
@Entity(tableName = "ledger_categories")
data class LedgerCategory(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val title: String = "",
    val kind: EntryKind = EntryKind.SPEND,
    /** Предел на месяц в копейках. 0 — предела нет. */
    val limit: Long = 0,
    /** Краска-метка. Пусто — выводится из названия, см. [MarkColor]. */
    val color: MarkColor? = null,
    val createdAt: LocalDateTime = LocalDateTime.now(),
)

/**
 * Запись в книге: сколько, куда, откуда и когда.
 *
 * [amount] всегда положительная, а знак несёт [kind]: минус, спрятанный в
 * сумме, рано или поздно складывают со вторым минусом и получают плюс.
 * Расход, доход, перевод и возврат отличаются не знаком числа, а тем, что с
 * деньгами произошло, — так они и записаны.
 *
 * У перевода заполнен [toAccountId] и пуст [categoryId]; у расхода, дохода и
 * возврата — наоборот. Двух записей на один перевод («ушло отсюда» и «пришло
 * туда») не заводится: это одно событие, и разъехаться половинами оно не
 * должно.
 *
 * У возврата ([EntryKind.BACK]) статья та же, что у траты, за которую вернули:
 * из неё возврат и вычитается. См. рассуждение при самом [EntryKind.BACK].
 *
 * Статьи может не быть и у траты — [categoryId] `null` значит «без статьи».
 * Требовать её значило бы задерживать запись ради вопроса, на который человек
 * у кассы отвечать не хочет; в итогах месяца такие траты стоят строкой
 * «Без статьи», и это честнее, чем сваленное в «Прочее».
 *
 * [removedAt] — та же корзина на сутки, что у дел, записей и строк Yet:
 * убранное живёт двадцать четыре часа, и «Вернуть» отменяет ошибку
 * по-настоящему.
 */
@Entity(
    tableName = "ledger_entries",
    indices = [Index("date"), Index("accountId"), Index("categoryId")],
)
data class LedgerEntry(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val date: LocalDate = LocalDate.now(),
    val kind: EntryKind = EntryKind.SPEND,
    /** Копейки, всегда больше нуля: знак несёт [kind]. */
    val amount: Long = 0,
    val accountId: Long = 0,
    /** Куда переложили. Только у перевода. */
    val toAccountId: Long? = null,
    /** Статья. `null` — «без статьи»: см. рассуждение выше. */
    val categoryId: Long? = null,
    val note: String = "",
    val createdAt: LocalDateTime = LocalDateTime.now(),
    val removedAt: LocalDateTime? = null,
)
