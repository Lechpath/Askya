package app.askya.data.entity

import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey
import java.time.LocalDateTime

/**
 * Запись в Scroll. Бывает двух видов, и различает их [uri]:
 *
 * - `uri == null` — текстовая заметка: заголовок и текст пишутся здесь же;
 * - `uri != null` — приложенный файл (pdf, md, картинка): содержимое лежит
 *   у системы, а здесь только ссылка на него и то, чем его открыть.
 *
 * Одной сущностью, а не двумя: в разделах они лежат вперемешку и сортируются
 * общим списком, а всё, чем они отличаются, — есть ли ссылка на файл.
 *
 * Файл не копируется внутрь приложения: хранится URI документа с постоянным
 * разрешением на чтение. Копия занимала бы место второй раз и устаревала бы
 * молча, когда человек правит файл в другом приложении.
 *
 * [topicId] `null` означает «без темы» — такие записи лежат в разделе «Файлы».
 * У картинок темы не бывает вовсе: «Изображения» отвязаны от «Книг» и собраны
 * своими папками — см. [albumId] и [ImageAlbum].
 *
 * Теги лежат списком строк прямо в записи, а не отдельной таблицей: для
 * фильтра по тегу этого достаточно, а join-таблица добавила бы сущность,
 * DAO и миграции без выигрыша.
 */
@Entity(
    tableName = "notes",
    indices = [Index("updatedAt"), Index("topicId"), Index("albumId"), Index("threadId")],
)
data class Note(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val title: String = "",
    val body: String = "",
    val tags: List<String> = emptyList(),
    val topicId: Long? = null,
    /**
     * Альбом картинки. `null` — «без альбома»: такая картинка видна в общей
     * сетке «Изображений» и больше нигде. Поле только для картинок: у заметок
     * и файлов есть книга, и складывать их ещё и в альбомы значило бы завести
     * второй способ раскладывать одно и то же.
     */
    val albumId: Long? = null,
    val uri: String? = null,
    val mime: String = "",
    /**
     * Картинка ли это. Считается один раз при добавлении и хранится: раздел
     * «Изображения» выбирает по этому полю, а разбирать mime в каждом запросе
     * SQL не умеет.
     */
    val isImage: Boolean = false,
    /**
     * Сколько длится голосовая заметка, в миллисекундах. У всего остального
     * ноль.
     *
     * Хранится, а не спрашивается у файла: «0:42» стоит в каждой строке
     * списка, а узнать длину звука можно только открыв его —
     * `MediaMetadataRetriever` на каждую строку при каждой прокрутке был бы
     * походом на диск за числом, которое известно в тот миг, когда запись
     * остановили. Ровно то же рассуждение, что у [isImage], только про длину.
     */
    val durationMs: Long = 0,
    /**
     * Нить, к которой запись относится. `null` — запись сама по себе.
     *
     * Не вместо книги ([topicId]) и не поверх неё: книга говорит, где запись
     * лежит на полке, нить — ради чего она написана. Замеры кухни лежат в
     * книге «Дом» и тянут нить «Кухня на Гоголя», и обе правды нужны.
     */
    val threadId: Long? = null,
    val createdAt: LocalDateTime = LocalDateTime.now(),
    val updatedAt: LocalDateTime = LocalDateTime.now(),
    /**
     * Когда запись убрали. `null` — на месте.
     *
     * Мягкое удаление, а не строка из базы вон: подтверждение «вы уверены?» не
     * отменяет ошибку, оно перекладывает её на человека, который торопится, — и
     * через месяц жмётся не читая. Убранное живёт сутки, снизу на несколько
     * секунд появляется «Вернуть», и подтверждений не нужно вовсе. Старое
     * подчищается при запуске приложения, без фоновой службы.
     */
    val removedAt: LocalDateTime? = null,
) {
    /**
     * Голосовая ли это заметка.
     *
     * По mime, а не по своей колонке: `audio/` в нём уже записано, и второй
     * признак того же самого пришлось бы держать в согласии с первым. У
     * картинок колонка есть ([isImage]), но по другой причине — их отбирают
     * запросами, а SQL разбирать mime не умеет так же дёшево, как читать флаг.
     */
    val voice: Boolean get() = mime.startsWith("audio/")
}
