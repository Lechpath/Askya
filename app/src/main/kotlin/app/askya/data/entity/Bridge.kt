package app.askya.data.entity

import androidx.room.Entity
import androidx.room.PrimaryKey
import app.askya.domain.model.BlockIcon

/**
 * Мост — именованная связь Askya с тем, что лежит вне её.
 *
 * ## Зачем
 *
 * Половина дел дня делается не в Askya, и это нормально. Кто-то читает в одной
 * читалке, кто-то в другой, кто-то созванивается в одном мессенджере, кто-то в
 * другом. Askya планирует день целиком, а открыть умела только то, что лежит
 * внутри неё: на самом частом деле дня человек упирался в стену и шёл искать
 * значок на рабочем столе руками.
 *
 * ## Почему мост живёт отдельно от дела
 *
 * Приложение меняется, а дело остаётся. Сменил читалку — переподключил один
 * мост, и все дела поехали за ним. Мост, привязанный к каждому делу по
 * отдельности, пришлось бы чинить полсотни раз.
 *
 * ## Чего здесь нет
 *
 * Ни одного имени чужого приложения. Askya не знает и не должна знать, чем
 * человек читает: она даёт мосты, а что к ним подключено, решает он. Как только
 * в коде появится «если это такое-то приложение, то…», Askya начнёт зависеть от
 * чужой прошивки и сломается на её следующем обновлении.
 *
 * [icon] — знак дела, к которому мост подключён, или `null`, если мост
 * подключают руками к строке списка или к отдельному делу. Знак — главный слой:
 * он угадывается по названию, и подключённая к «чтению» читалка ведёт из всех
 * дел про чтение, включая те, что появятся завтра.
 */
@Entity(tableName = "bridges")
data class Bridge(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    /** Как мост называется человеку: «Читалка», «Созвон», «Заметки по работе». */
    val name: String = "",
    /** Имя пакета либо адрес — смотря какой [kind]. */
    val target: String = "",
    val kind: BridgeKind = BridgeKind.APP,
    val icon: BlockIcon? = null,
    /**
     * Когда мостом пользовались в последний раз, в миллисекундах эпохи.
     *
     * Нужно списку выбора: приложений на телефоне полторы сотни, и наверх
     * поднимается то, что брали недавно. Ноль — ни разу.
     */
    val usedAt: Long = 0,
)

/**
 * Чем оканчивается мост.
 *
 * Ссылка нужна там, где приложение принимает глубокие ссылки и умеет открыться
 * не просто на главной, а в нужном месте. Какие именно — дело человека: Askya в
 * это не вмешивается и ничего в адресе не разбирает.
 */
enum class BridgeKind(val title: String) {
    APP("Приложение"),
    LINK("Ссылка"),
}
