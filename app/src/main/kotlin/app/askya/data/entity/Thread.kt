import java.time.LocalDate
import java.time.LocalDateTime

/**
 * Нить — личное начинание, которое тянется через разделы.
 *
 * ## Своего у неё пять полей, и это нарочно
 *
 * Готового нить не хранит. Дела по ней лежат в расписании, строки — в списке
 * Yet, траты — в книге, замеры — в записи Scroll; нить только собирает их
 * вместе и говорит, жива ли она. Заведи ей второе расписание и второй список —
 * и в Askya появилось бы второе место для того же самого, а человеку пришлось
 * бы помнить, куда он это записал.
 *
 * Своё у нити одно, и оно не повторяет ни одного раздела: **карта замысла**
 * ([ThreadNode], [ThreadEdge]). Искры, пути, подводные камни и открытия
 * положить было решительно некуда — в расписании им нет дня, в списке они
 * становятся задачами, которых никто не ставил. Карта стоит **до** дел: из неё
 * они и вырастают.
 *
 * Названа `ThreadItem`, а не `Thread`: в Kotlin `Thread` — это поток
 * исполнения из `java.lang`, и класс с таким именем перекрывал бы его в каждом
 * файле, где нить упомянута. Имя в том же ряду, что `RoutineItem` и `YetItem`.
 *
 * ## Пульса в таблице нет
 *
 * «Когда трогали в последний раз» не колонка, а вопрос к делам, тратам и
 * строкам этой нити (`ThreadDao.observeTouches`). Колонка была бы вторым
 * источником правды: отметил дело — обновили колонку, отменил отметку — забыли
 * обновить, и нить говорит, что её трогали, когда её не трогали. То же
 * рассуждение, по которому в Ledger нигде не хранится остаток счёта.
 *
 * ## Закрытая нить не удаляется
 *
 * Ни доведённая, ни брошенная. На нити висят месяцы, в которые она шла, и
 * стереть её значило бы стереть их. [closedAt] помнит, когда это случилось, —
 * «Закончена 14 июня» человек читает как запись о случившемся, а не как
 * состояние галочки.
 */
@Entity(tableName = "threads")
data class ThreadItem(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val title: String = "",
    /**
     * Чем она закончится — одна строка своими словами: «машина встанет
     * внутрь», «говорю с носителем полчаса».
     *
     * Не обязательна, но спрашивается сразу: нить без описанного конца — это
     * настроение, а не нить, и через месяц по ней нельзя понять, чего же
     * хотели. Придумывать конец за человека приложение не берётся.
     */
    val ending: String = "",
    /** Краска-метка. Пусто — выводится из названия, см. [MarkColor]. */
    val color: MarkColor? = null,
    val state: ThreadState = ThreadState.GROWING,
    /** Срок. `null` — без срока, и у большинства нитей его нет. */
    val due: LocalDate? = null,
    /**
     * Сколько заложено, в копейках. 0 — не закладывали.
     *
     * Копейками и главной валютой: смета нужна ремонту и поездке, а они
     * считаются в том же, в чём считается книга. Валютные траты в неё не
     * входят по той же причине, по какой не входят в месяц (см. `Currency`).
     */
    val budget: Long = 0,
    val createdAt: LocalDateTime = LocalDateTime.now(),
    /** Когда нить закрыли — довели или бросили. `null` у идущей и отложенной. */
    val closedAt: LocalDateTime? = null,
)

/**
 * Узел карты — карточка, из которых сплетается замысел.
 *
 * ## Место хранится числами, а не порядком
 *
 * [x] и [y] — то, куда человек передвинул карточку пальцем. Списком с полем
 * `position` карту не описать: в ней нет «первого» и «третьего», в ней есть
 * «вот это сбоку, а вон то ниже и правее». Дробными, а не целыми клетками:
 * карточка встаёт там, где её отпустили, а не прыгает в сетку — прыжок читался
 * бы как «приложение знает лучше».
 *
 * Новый узел место себе выбирает сам ([app.askya.domain.model.placeNear]):
 * человек, пришедший записать мысль, не должен в ту же секунду заниматься
 * раскладкой.
 *
 * ## Привязка одна и та же, что у дела
 *
 * [link] хранит пару «вид: адрес» ровно так же, как колонка дела
 * ([app.askya.domain.model.DeedLink]): `book:12`, `note:87`, `yet:3`. Значит,
 * к узлу можно привязать книгу Библиотеки, запись Scroll, список, плейлист —
 * всё, что уже лежит в приложении, и без единой новой колонки на каждый вид.
 *
 * [deedId] стоит отдельно и означает другое: не «чем это делается», а «этот шаг
 * поставлен делом на такой-то день». Дело живёт в расписании обычной строкой,
 * узел лишь помнит его номер, чтобы показать отметку и не завести второе такое
 * же.
 *
 * ## Почему отметка — время, а не галочка
 *
 * [doneAt] помнит **когда**. Из этого складывается список побед и пульс нити:
 * «шаг сделан» без дня не говорит ничего, а «сделан во вторник» — говорит.
 */
@Entity(
    tableName = "thread_nodes",
    indices = [Index("threadId")],
)
data class ThreadNode(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val threadId: Long = 0,
    val kind: ThreadNodeKind = ThreadNodeKind.THOUGHT,
    /** Сам узел одной строкой — то, что видно на карте. */
    val title: String = "",
    /** Развёрнутое: то, что не помещается на карточку и открывается в ней. */
    val note: String = "",
    val x: Float = 0f,
    val y: Float = 0f,
    /** Привязка к тому, что уже лежит в Askya. Пусто — узел сам по себе. */
    val link: String? = null,
    /** Дело в расписании, поставленное из этого шага. `null` — не ставили. */
    val deedId: Long? = null,
    /** Когда шаг сделан, а результат — достигнут. `null` — ещё нет. */
    val doneAt: LocalDateTime? = null,
    val createdAt: LocalDateTime = LocalDateTime.now(),
) {
    /** Место на карте — в том виде, в каком его считает домен. */
    val spot: Spot get() = Spot(x, y)

    /** Насколько крупно узел стоит: у сделанного шага размер тот же. */
    val size: NodeSize get() = kind.size

    /** Сделан ли — для тех типов, которые вообще отмечают. */
    val done: Boolean get() = doneAt != null

    /** Каким его видит счёт побед: без места и без текста. */
    fun fact(): ThreadNodeFact = ThreadNodeFact(
        id = id,
        kind = kind,
        title = title,
        madeOn = createdAt.toLocalDate(),
        doneOn = doneAt?.toLocalDate(),
    )
}

/**
 * Связь между двумя узлами: «вот это выросло из вон того».
 *
 * ## Почему отдельной таблицей, а не колонкой «родитель»
 *
 * Колонка `parentId` описывает дерево, а замысел деревом не бывает. Один шаг
 * отвечает сразу двум путям; открытие приходит из шага, а меняет результат;
 * обход камня тянется и к камню, и к пути, который его обошёл. Дерево заставило
 * бы выбирать, чьим ребёнком считать такой узел, — и человек выбирал бы
 * неправду.
 *
 * ## Направление есть, стрелок нет
 *
 * [fromId] — то, из чего выросло; [toId] — то, что выросло. Направление хранится
 * потому, что оно и есть история замысла: по нему видно, откуда взялась мысль.
 * Рисовать его стрелками на карте не обязательно — линия и так читается сверху
 * вниз, а карта, утыканная стрелками, превращается в схему предприятия.
 */
@Entity(
    tableName = "thread_edges",
    indices = [Index("threadId"), Index("fromId"), Index("toId")],
)
data class ThreadEdge(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val threadId: Long = 0,
    /** Из чего выросло. */
    val fromId: Long = 0,
    /** Что выросло. */
    val toId: Long = 0,
    val createdAt: LocalDateTime = LocalDateTime.now(),
)
