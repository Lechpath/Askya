package app.askya.weather

import java.time.LocalDate
import java.time.LocalDateTime

/** Погода сейчас. */
data class WeatherNow(
    val temperature: Int,
    val feelsLike: Int,
    val code: Int,
    /** День на улице или ночь — по этому же коду солнце меняется на луну. */
    val day: Boolean,
    val windKmh: Int,
    val humidity: Int,
)

/** Час прогноза. */
data class WeatherHour(
    val at: LocalDateTime,
    val temperature: Int,
    val code: Int,
    /** Вероятность осадков, проценты. */
    val rainChance: Int,
)

/** День прогноза. */
data class WeatherDay(
    val date: LocalDate,
    val min: Int,
    val max: Int,
    val code: Int,
    val rainChance: Int,
    val sunrise: String,
    val sunset: String,
)

/**
 * Всё, что известно о погоде: место, сейчас, по часам и по дням.
 *
 * [place] — название места словами; пустое означает, что система его не
 * назвала. Погода от этого не портится, и показывается она всё равно — просто
 * без подписи.
 *
 * [fetchedAt] — когда это спрашивали, в миллисекундах. По нему решается,
 * пора ли спрашивать снова, и по нему же в разделе пишется «данные такой-то
 * давности», когда сети нет.
 */
data class Forecast(
    val place: String,
    val now: WeatherNow,
    val hours: List<WeatherHour>,
    val days: List<WeatherDay>,
    val fetchedAt: Long,
)

/**
 * Погода словами — по коду WMO.
 *
 * Коды эти международные и приходят числами; свой список нужен потому, что
 * названия у них английские и канцелярские («Thunderstorm with slight hail»).
 * Здесь они сказаны так, как о погоде говорят: «гроза с градом».
 *
 * Соседние коды сведены в одно слово там, где разница не про то, что видно из
 * окна: морось слабая, средняя и сильная — это всё морось.
 */
fun weatherWords(code: Int): String = when (code) {
    0 -> "Ясно"
    1 -> "Почти ясно"
    2 -> "Переменная облачность"
    3 -> "Пасмурно"
    45, 48 -> "Туман"
    51, 53, 55 -> "Морось"
    56, 57 -> "Ледяная морось"
    61 -> "Небольшой дождь"
    63 -> "Дождь"
    65 -> "Сильный дождь"
    66, 67 -> "Ледяной дождь"
    71 -> "Небольшой снег"
    73 -> "Снег"
    75 -> "Сильный снег"
    77 -> "Снежная крупа"
    80, 81 -> "Ливень"
    82 -> "Сильный ливень"
    85, 86 -> "Снежные заряды"
    95 -> "Гроза"
    96, 99 -> "Гроза с градом"
    else -> "Погода"
}

/**
 * Погода знаком.
 *
 * Знаки взяты буквами Юникода, а не рисунками: своих значков погоды в Askya
 * нет, а рисовать два десятка (и ещё столько же ночных) ради строчки в меню —
 * работа, несоразмерная месту, которое они займут.
 *
 * Ночь меняет только ясное и почти ясное: под дождём и в тумане луны всё равно
 * не видно.
 */
fun weatherMark(code: Int, day: Boolean = true): String = when (code) {
    0 -> if (day) "☀" else "☾"
    1 -> if (day) "🌤" else "☾"
    2 -> "⛅"
    3 -> "☁"
    45, 48 -> "🌫"
    51, 53, 55, 56, 57 -> "🌦"
    61, 63, 65, 66, 67, 80, 81, 82 -> "🌧"
    71, 73, 75, 77, 85, 86 -> "❄"
    95, 96, 99 -> "⛈"
    else -> "•"
}

/** Температура так, как её пишут: со знаком и градусом. */
fun formatDegrees(value: Int): String = if (value > 0) "+$value°" else "$value°"

/**
 * Место, найденное по названию.
 *
 * Приходит из геокодера Open-Meteo — того же источника, что и сама погода, и
 * так же без ключа. Нужно оно ровно для одного: человек набирает «Казань»,
 * выбирает строку, и в настройках погоды остаются широта с долготой. Дальше
 * геокодер не спрашивается больше никогда.
 *
 * [region] — что стоит под названием: страна и область. Без него список из
 * восьми «Москва» неразличим, а Москв на свете больше одной.
 */
data class FoundPlace(
    val name: String,
    val region: String,
    val latitude: Double,
    val longitude: Double,
)
