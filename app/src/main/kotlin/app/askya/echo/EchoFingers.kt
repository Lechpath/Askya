package app.askya.echo

/**
 * На чём это играют.
 *
 * Три инструмента, и они не случайные: гитара — то, подо что поют; укулеле —
 * то, что берут, когда гитары нет и учиться некогда; клавиши — то, на чём
 * аккорд виден целиком, без всякой аппликатуры. Четвёртым напрашивалось
 * фортепиано отдельно от синтезатора, но это один и тот же ряд клавиш.
 *
 * [strings] — открытые струны снизу вверх, от толстой к тонкой, названиями
 * нот. У клавиш струн нет, и список пуст: их аккорд рисуется рядом клавиш, а
 * не сеткой ладов.
 */
enum class EchoInstrument(
    val title: String,
    val strings: List<String>,
) {
    GUITAR("Гитара", listOf("E", "A", "D", "G", "B", "E")),
    UKULELE("Укулеле", listOf("G", "C", "E", "A")),
    KEYS("Клавиши", emptyList()),
}

/**
 * Как аккорд лежит на грифе.
 *
 * Число на струну, снизу вверх: −1 — струна глушится, 0 — открытая, дальше —
 * номер лада. Пустой список — у инструмента нет грифа (клавиши).
 *
 * ## Почему таблицей, а не расчётом
 *
 * Аппликатуру можно вывести: взять три ноты аккорда и найти, где они лежат под
 * рукой. Вывод даёт формально верные хваты, которых не берёт никто: гитарист
 * играет C как `x32010` не потому, что это единственное решение, а потому что
 * так его учили, так он видит его в песеннике и так рука встаёт сама.
 * Двадцать четыре строчки таблицы — это то, что человек узнает, а расчёт — то,
 * что ему придётся разбирать.
 *
 * Баррэ в таблице честное: у половины аккордов открытого хвата не бывает, и
 * подставлять вместо `F` что-то полегче значит врать. Зато и стоит `F` там,
 * где стоит, — на первом ладу, а не на восьмом: рука ищет ближний.
 */
fun fingering(chord: EchoChord, instrument: EchoInstrument): List<Int> = when (instrument) {
    EchoInstrument.GUITAR -> if (chord.minor) GUITAR_MINOR[chord.root] else GUITAR_MAJOR[chord.root]
    EchoInstrument.UKULELE -> if (chord.minor) UKULELE_MINOR[chord.root] else UKULELE_MAJOR[chord.root]
    EchoInstrument.KEYS -> emptyList()
}

/**
 * Ноты аккорда буквами — то, чем он берётся на клавишах.
 *
 * Три ноты и ничего больше: левая рука берёт основание, правая — трезвучие, и
 * какими именно октавами, решает тот, кто играет. Расписывать за него
 * обращения значило бы учить музыке, а здесь всего лишь называют аккорд.
 */
fun keysOf(chord: EchoChord): List<String> = chord.notes.map { NOTE_NAMES[it] }

// Гитара, стандартный строй. Снизу вверх: E A D G B E.
private val GUITAR_MAJOR = listOf(
    listOf(-1, 3, 2, 0, 1, 0), // C
    listOf(-1, 4, 6, 6, 6, 4), // C#
    listOf(-1, -1, 0, 2, 3, 2), // D
    listOf(-1, 6, 8, 8, 8, 6), // Eb
    listOf(0, 2, 2, 1, 0, 0), // E
    listOf(1, 3, 3, 2, 1, 1), // F
    listOf(2, 4, 4, 3, 2, 2), // F#
    listOf(3, 2, 0, 0, 0, 3), // G
    listOf(4, 6, 6, 5, 4, 4), // Ab
    listOf(-1, 0, 2, 2, 2, 0), // A
    listOf(-1, 1, 3, 3, 3, 1), // Bb
    listOf(-1, 2, 4, 4, 4, 2), // B
)

private val GUITAR_MINOR = listOf(
    listOf(-1, 3, 5, 5, 4, 3), // Cm
    listOf(-1, 4, 6, 6, 5, 4), // C#m
    listOf(-1, -1, 0, 2, 3, 1), // Dm
    listOf(-1, 6, 8, 8, 7, 6), // Ebm
    listOf(0, 2, 2, 0, 0, 0), // Em
    listOf(1, 3, 3, 1, 1, 1), // Fm
    listOf(2, 4, 4, 2, 2, 2), // F#m
    listOf(3, 5, 5, 3, 3, 3), // Gm
    listOf(4, 6, 6, 4, 4, 4), // Abm
    listOf(-1, 0, 2, 2, 1, 0), // Am
    listOf(-1, 1, 3, 3, 2, 1), // Bbm
    listOf(-1, 2, 4, 4, 3, 2), // Bm
)

// Укулеле, строй G C E A.
private val UKULELE_MAJOR = listOf(
