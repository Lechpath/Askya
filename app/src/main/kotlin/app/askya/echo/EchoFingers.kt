    listOf(3, 3, 3, 1), // Eb
    listOf(1, 4, 0, 2), // E
    listOf(2, 0, 1, 0), // F
    listOf(3, 1, 2, 1), // F#
    listOf(0, 2, 3, 2), // G
    listOf(1, 3, 4, 3), // Ab
    listOf(2, 1, 0, 0), // A
    listOf(3, 2, 1, 1), // Bb
    listOf(4, 3, 2, 2), // B
)

private val UKULELE_MINOR = listOf(
