    listOf(2, 1, 2, 0), // F#m
    listOf(0, 2, 3, 1), // Gm
    listOf(1, 3, 4, 2), // Abm
    listOf(2, 0, 0, 0), // Am
    listOf(3, 1, 1, 1), // Bbm
    listOf(4, 2, 2, 2), // Bm
)
