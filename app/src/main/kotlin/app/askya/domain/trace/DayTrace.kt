package app.askya.domain.trace

import java.time.LocalTime

/**
 * «Что было» — день, собранный из следов, которые оставили разделы.
 *
 * ## Зачем
 *
 * Разделы Askya живут порознь и не знают друг о друге: расписание не знает о
 * тратах, Ledger — о записях, Scroll — о списках. Так и задумано, и менять это
 * незачем. Но человек-то один, и день у него один: он записал заметку, отметил
 * два дела, потратил на обед и дописал строку в список — и всё это случилось в
 * одном дне и в одном порядке.
 *
 * Этот слой не заводит своих данных и не ведёт своей летописи. Он спрашивает у
 * тех же таблиц, из которых разделы читают сами, и складывает ответы в один
 * список по часам. Ни одной новой строки в базе, ни одной копии.
 *
 * ## Почему без Echo и AskyaV
 *
 * Их здесь нет, и это не забывчивость. **Такого следа не существует.** Echo
 * помнит одну последнюю дорожку — ту, с которой продолжают, — и никакой
 * истории прослушанного не ведёт. AskyaV помнит, до какой минуты досмотрен
 * каждый файл, но не помнит, **когда** его смотрели: у отметки нет часа.
 *
 * Спросить у них «что было вчера» нельзя, потому что вчерашнего они не
 * помнят. Завести им память — отдельное решение и отдельная строка в
 * хранилище; выдумывать её здесь значило бы показать человеку не то, что
 * было, а то, что похоже на правду.
 *
 * ## Это фундамент
 *
 * Ни сети, ни моделей: слой только собирает и отдаёт. Собеседник, если он
 * однажды будет, вырастет на этом же списке — но сегодня список сам себе цель.
 */
enum class TracePart(val title: String) {
    DAY("День"),
    SCROLL("Scroll"),
    LEDGER("Ledger"),
    YET("Списки"),
    REMINDERS("Напоминания"),
}

/**
 * Один след дня.
 *
 * [at] — час, если он у следа есть. У заметки он есть всегда, у отмеченного
 * дела — час самого дела, а у списка, тронутого за день, часа может не быть
 * вовсе. `null` означает «было в этот день», а не «было в полночь», и внизу
 * такие стоят не потому, что случились позже, а потому, что о часе им сказать
 * нечего.
 *
 * [gist] — короткая суть, одной строкой: то, что человек сам написал. Askya
 * ничего не пересказывает своими словами.
 *
 * [aside] — приписка справа: сумма у траты, «голос» у надиктованного. Пусто —
 * приписки нет, и это обычное дело.
 */
data class DayEvent(
    val at: LocalTime?,
    val part: TracePart,
    val gist: String,
    val aside: String = "",
)

/**
 * След дня по порядку: сперва то, у чего есть час, — по часам; следом
 * бесчасовое — в порядке разделов.
 *
 * Внутри одного часа порядок разделов постоянный, а не случайный: два события
 * в 12:30 должны при каждой перерисовке стоять одинаково, иначе список
 * подрагивает на каждом обновлении базы.
 */
fun orderedTrace(events: List<DayEvent>): List<DayEvent> {
    val timed = events.filter { it.at != null }
        .sortedWith(compareBy({ it.at }, { it.part.ordinal }, { it.gist }))
    val untimed = events.filter { it.at == null }
        .sortedWith(compareBy({ it.part.ordinal }, { it.gist }))
    return timed + untimed
}

/**
 * Суть одной строкой: первая непустая строка написанного, ужатая до меры.
 *
 * Заметка бывает в страницу, и в карточке дня ей не место — но и «Заметка»
 * вместо её первой строки не говорит ничего. Обрывается по слову, а не по
 * букве: «Позвонить Ал…» читается хуже, чем «Позвонить…».
 */
fun gistOf(source: String, limit: Int = 48, fallback: String = "Без названия"): String {
    val first = source.lineSequence()
        .map { it.trim() }
        .firstOrNull { it.isNotEmpty() }
        ?: return fallback

    if (first.length <= limit) return first

    val cut = first.take(limit)
    val space = cut.lastIndexOf(' ')
    val kept = if (space > limit / 2) cut.take(space) else cut
    return kept.trimEnd(' ', ',', '.', '—', '-') + "…"
}
