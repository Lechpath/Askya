package app.askya.domain.model

/**
 * Чем делается дело — привязка дела к тому, что уже лежит в Askya.
 *
 * ## Зачем
 *
 * В приложении есть книга с запомненным местом, плейлист на вечер, заметка по
 * объекту и список Yet. И есть день, в котором про всё это написано словами.
 * Нажать на дело и попасть в то, чем его делают, было нельзя ни разу: разделы
 * написаны, каждый хорош по отдельности, и ни один не знал о соседе. Привязка —
 * не новый раздел, а склейка уже написанного.
 *
 * ## Почему одной строкой
 *
 * Пара «вид + адрес» лежит в одной колонке — `book:12`, `yet:3`, `note:87`, —
 * а не пятью колонками с номерами. Видов будет прибавляться, и следующий из
 * них внешний: «Мост» ведёт не внутрь Askya, а в другое приложение телефона,
 * и колонки `bridgeId` рядом с `bookId` означали бы новую миграцию на каждый
 * вид. Одна строка переживает их все.
 *
 * Неизвестный вид сводится к «нет привязки», а не роняет чтение, — так же, как
 * это сделано с перечислениями в базе: запись из будущей версии не должна
 * ломать сегодняшнюю.
 */
enum class LinkKind(
    /** Как вид записан в базе. Меняться не должен: это уже записанные строки. */
    val key: String,
    /** Как вид называется человеку в выборе. */
    val title: String,
    /** Есть ли у вида адрес. У раздела его нет — он один. */
    val addressed: Boolean = true,
) {
    /**
     * Мост — единственный вид, ведущий не внутрь Askya, а наружу: в другое
     * приложение телефона или по ссылке. Ради него привязка и хранится парой
     * «вид + адрес» одной строкой, а не колонкой на каждый вид.
     */
    BRIDGE("bridge", "Мост"),
    BOOK("book", "Книга"),
    NOTE("note", "Запись"),
    YET("yet", "Список Yet"),
    ECHO("echo", "AskyaEcho", addressed = false),
    VIDEO("video", "AskyaV", addressed = false),
    ;

    companion object {
        fun of(key: String): LinkKind? = entries.firstOrNull { it.key == key }
    }
}

/**
 * Привязка дела: вид и адрес внутри вида.
 *
 * [id] у безадресных видов равен нулю и не значит ничего: в AskyaEcho и AskyaV
 * ведёт сам раздел, а где именно человек остановился, эти разделы помнят сами.
 */
data class DeedLink(val kind: LinkKind, val id: Long = 0L) {

    /** Как эта привязка ложится в колонку. */
    fun store(): String = if (kind.addressed) "${kind.key}:$id" else kind.key

    companion object {

        /**
         * Разобрать записанное. Пусто, мусор или неизвестный вид — `null`, то
         * есть «нет привязки»: дело без привязки открывается как раньше, и это
         * лучше, чем упасть на строке, записанной версией, которой ещё нет.
         */
        fun of(raw: String?): DeedLink? {
            val text = raw?.trim().orEmpty()
            if (text.isEmpty()) return null
            val kind = LinkKind.of(text.substringBefore(':')) ?: return null
            if (!kind.addressed) return DeedLink(kind)
            val id = text.substringAfter(':', "").toLongOrNull() ?: return null
            if (id <= 0L) return null
            return DeedLink(kind, id)
        }
    }
}
