package app.askya.domain.model

import java.time.LocalDate
import java.time.YearMonth
import java.time.temporal.ChronoUnit

/**
 * Нить — то, что тянется неделями и умирает не от провала, а от тишины.
 *
 * ## Зачем понадобился шестой раздел
 *
 * Пять разделов Askya нарезаны по роду вещи: время (AskyaDay), написанное
 * (Scroll), музыка, видео, деньги (Ledger). Личное начинание идёт поперёк всех
 * сразу: у ремонта есть и дела, и траты, и список «купить», и замеры в записи;
 * у языка — дела по вторникам и тетрадь слов. Спросить «как оно вообще идёт»
 * было нельзя нигде: каждый раздел знает свою половину и не знает соседа.
 *
 * Нить и есть этот вопрос, заданный вслух. Своего содержимого у неё почти нет
 * — она **тянется через разделы** и собирает то, что уже записано в них.
 *
 * ## Почему не процент готовности
 *
 * Потому что его нельзя назвать честно. «Ремонт готов на 70 %» — это не
 * знание, а самочувствие, и приложение, которое рисует такую цифру, врёт с
 * точностью до десятых. Зато в базе лежит факт: в какие дни по нити что-то
 * происходило. Из него и считается всё, что раздел говорит, — последнее
 * касание и сколько их было по месяцам ([pulseOf]).
 *
 * Это ровно то же рассуждение, по которому в «Прожитом» нет ни целей, ни
 * очков, ни «привычек»: считается то, что человек отметил сам, и ничего сверх.
 *
 * ## Почему «брошена» — такое же состояние, как «закончена»
 *
 * Приложения обычно знают два ответа: сделано и не сделано, — и всякое
 * незаконченное начинание висит вечным упрёком. Человек имеет право сказать
 * «я это бросил», и Askya обязана принять этот ответ как обычный. Брошенная
 * нить не удаляется: на ней висит история, и стереть её значило бы стереть те
 * месяцы, когда она шла.
 */
enum class ThreadState(val title: String) {
    LIVE("Идёт"),
    PAUSED("Отложена"),
    DONE("Закончена"),
    DROPPED("Брошена"),
    ;

    /** Тянется ли нить сейчас: у отложенной и закрытой пульса не спрашивают. */
    val running: Boolean get() = this == LIVE

    /** Закрыта ли она — всё равно, доведена или брошена. */
    val closed: Boolean get() = this == DONE || this == DROPPED

    companion object {
        /** Из строки в базе. Неизвестное — «идёт»: см. [MarkColor] и прочие. */
        fun of(name: String?): ThreadState = entries.firstOrNull { it.name == name } ?: LIVE
    }
}

/** Сколько дней месяца нить двигалась. */
data class ThreadMonth(val month: YearMonth, val days: Int)

/**
 * Пульс нити: когда её трогали в последний раз и как часто до этого.
 *
 * [last] — самое позднее касание за всю жизнь нити, а не за показанный срок:
 * нить, брошенная год назад, должна уметь сказать про тот год. `null` значит
 * «не трогали ни разу» — так выглядит только что заведённая нить.
 *
 * [months] — ровно [PULSE_MONTHS] клеток подряд, включая пустые: полоска из
 * шести столбиков, в которой три отсутствуют, читается хуже, чем полоска, где
 * три стоят пустыми. Пустой месяц — это и есть новость.
 *
 * [days] — сколько всего дней внутри показанного срока. Не «касаний»: два дела
 * в один день это один день работы, и складывать их значило бы хвалить за
 * подряд поставленные галочки.
 */
data class ThreadPulse(
    val last: LocalDate? = null,
    val months: List<ThreadMonth> = emptyList(),
    val days: Int = 0,
) {
    /** Сколько дней тишины. `null` — нить не трогали вовсе. */
    fun silence(today: LocalDate): Long? =
        last?.let { ChronoUnit.DAYS.between(it, today).coerceAtLeast(0) }
}

/**
 * Полгода — тот срок, на котором виден и ход, и остановка.
 *
 * Год не помещается в полоску телефона по-человечески: двенадцать столбиков в
 * ширину карточки — это волоски. Три месяца слишком коротки: нить, которую
 * ведут раз в две недели, выглядела бы в них замершей.
 */
const val PULSE_MONTHS = 6

/**
 * Считает пульс по дням, в которые нить двигалась.
 *
 * [touches] приходят как есть, с повторами и вперемешку: один день, в который
 * отметили дело и записали трату, приходит дважды, и складывать его дважды
 * нельзя — считаются **дни**, а не события.
 *
 * [through] — последний месяц полоски, обычно нынешний. Задаётся снаружи, а не
 * берётся у часов, чтобы счёт можно было проверить тестом: «сегодня» внутри
 * чистой функции делает её непроверяемой.
 *
 * Дни из будущего не выбрасываются: запись с опиской в дате — такой же факт,
 * как остальные, и прятать её значило бы повторить ту историю, когда трата,
 * уехавшая в будущий год, пропадала из виду, но продолжала считаться.
 */
fun pulseOf(
    touches: List<LocalDate>,
    through: YearMonth,
    span: Int = PULSE_MONTHS,
): ThreadPulse {
    val days = touches.toSet()

    val window = (0 until span).map { back -> through.minusMonths((span - 1 - back).toLong()) }
    val byMonth = days.groupingBy { YearMonth.from(it) }.eachCount()

    return ThreadPulse(
        last = days.maxOrNull(),
        months = window.map { month -> ThreadMonth(month, byMonth[month] ?: 0) },
        days = days.count { YearMonth.from(it) in window },
    )
}

/**
 * Сколько тишины считать поводом спросить.
 *
 * Полтора месяца, а не неделя и не полгода. Неделя — это отпуск, болезнь и
 * просто занятая неделя; спрашивать после неё значит стать ещё одним
 * приложением, которое дёргает. Полгода — это когда спрашивать уже поздно:
 * человек к тому времени сам всё понял и просто не хочет открывать раздел.
 */
const val SILENT_DAYS = 45

/**
 * Пора ли спросить у человека, что с этой нитью.
 *
 * Только у идущей: у отложенной тишина и есть её состояние, а закрытую
 * спрашивать не о чем.
 */
fun asksAbout(state: ThreadState, pulse: ThreadPulse, today: LocalDate): Boolean {
    if (!state.running) return false
    val silence = pulse.silence(today) ?: return false
    return silence >= SILENT_DAYS
}

/**
 * «вчера», «3 дня», «47 дней», «полтора месяца» — тишина человеческими словами.
 *
 * Днями до двух месяцев, дальше месяцами: «девяносто четыре дня» человек всё
 * равно переводит в уме, а «три месяца» — это уже ответ. Первые сутки названы
 * словом: «вчера» короче и точнее, чем «1 день».
 */
fun silenceWord(days: Long): String = when {
    days <= 0 -> "сегодня"
    days == 1L -> "вчера"
    days < 60 -> "$days ${dayWord(days)}"
    else -> {
        val months = days / 30
        "$months ${monthWord(months)}"
    }
}

private fun dayWord(count: Long): String {
    val last = count % 10
    val hundred = count % 100
    return when {
        hundred in 11..14 -> "дней"
        last == 1L -> "день"
        last in 2..4 -> "дня"
        else -> "дней"
    }
}

private fun monthWord(count: Long): String {
    val last = count % 10
    val hundred = count % 100
    return when {
        hundred in 11..14 -> "месяцев"
        last == 1L -> "месяц"
        last in 2..4 -> "месяца"
        else -> "месяцев"
    }
}
