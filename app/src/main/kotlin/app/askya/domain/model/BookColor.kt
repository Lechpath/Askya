package app.askya.domain.model

/**
 * Цвет корешка книги — то, чем книгу узнают на полке раньше, чем прочитают
 * название.
 *
 * Выбирается руками. Пусто значит «не выбирали»: тогда цвет выводится из
 * названия — книга всё равно окрашена, и полка не выглядит списком, но человек
 * не обязан выбирать цвет каждой заведённой книге.
 *
 * Порядок здесь — порядок в палитре выбора: тёплые, потом холодные, потом
 * тёмные. Хранится имя константы, а не номер, поэтому порядок можно менять
 * дальше, не трогая уже выбранное.
 */
enum class BookColor {
    CORAL,
    AMBER,
    ROSE,
    GREEN,
    BLUE,
    PLUM,
    BROWN,
    INK,
}
