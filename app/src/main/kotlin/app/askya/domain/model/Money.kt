package app.askya.domain.model

/**
 * Деньги в Askya и то, чем они бывают записаны.
 *
 * ## Копейки целым числом, и никогда не дробью
 *
 * Всякая сумма здесь — целое число копеек (`Long`). Не рубли дробью и тем
 * более не `Double`: 0,1 + 0,2 в двоичной дроби не даёт 0,3, и книга, в
 * которой сто записей, к концу месяца расходится с самой собой на копейку.
 * Копейку эту потом не найти — она не ошибка ввода, а свойство чисел, — и
 * доверять такой книге нельзя. Целые копейки складываются точно, а рублями
 * они становятся только на экране ([formatMoney]).
 *
 * Long, а не Int: в копейках миллион рублей — это сто миллионов, и Int
 * кончается на двадцати одном миллионе рублей. Не бог весть какое состояние
 * для книги, которую ведут годами.
 *
 * ## Одна валюта
 *
 * Рубль, и знак его не спрашивается. Курсы валют — это сеть, ежедневный поход
 * за чужими числами и вопрос «по какому курсу считать вчерашнюю покупку», на
 * который нет одного верного ответа. Askya в сеть ходит за одной погодой (и
 * будет ходить), а книга ведётся про одну жизнь, у которой обычно одна валюта.
 * Кому нужна вторая — заводит второй счёт и считает в нём своим умом; врать
 * ему приложение при этом не будет.
 */

/** Что записано: расход, доход, перевод между своими счетами или возврат. */
enum class EntryKind(val title: String, val one: String) {
    SPEND("Расходы", "Расход"),
    EARN("Доходы", "Доход"),

    /**
     * Перевод — единственная запись, у которой два счёта и ни одной статьи.
     *
     * Ни доходом, ни расходом он не считается нигде: переложить из кошелька на
     * карту — не трата, и в итоге месяца ему делать нечего. Иначе всякий поход
     * к банкомату выглядел бы тратой и заодно доходом того же размера, а
     * «сколько я потратил в августе» переставало бы что-либо значить.
     */
    MOVE("Переводы", "Перевод"),

    /**
     * Возврат — деньги, вернувшиеся за трату, которая была не своя.
     *
     * Заплатил за другого — купил кому-то билет, скинулся за всех в кафе,
     * вынул из своего кошелька то, что человек должен был вынуть из своего, —
     * а потом он отдал. Со счётом при этом случилось то же, что при доходе:
     * денег прибавилось. С бюджетом — прямо обратное: этой траты у вас как бы
     * и не было.
     *
     * Поэтому возврат не доход, и записывать его доходом нельзя: месяц, в
     * котором «пришло» больше зарплаты, потому что за вас вернули за такси,
     * врёт про заработок. Возврат **вычитается из расхода** — из общего «ушло»
     * и из той статьи, по которой трата прошла. Купили еды на чужие две
     * тысячи, вернули две тысячи — по «Еде» осталось ровно то, что съели вы,
     * и предел месяца на неё не потрачен.
     *
     * Отсюда и то, что возврат может увести месяц в минус по статье: вернули в
     * сентябре за августовскую трату — в сентябре по этой статье выйдет минус.
     * Это не поломка счёта, а правда о том, когда деньги ходили; трогать
     * прошлый месяц задним числом книга не станет.
     *
     * Статья у возврата та же, что была у траты, и она не обязательна: без неё
     * возврат уменьшает «ушло», не трогая ни одной статьи.
     */
    BACK("Возвраты", "Возврат"),
    ;

    /**
     * По какому словарю статей выбирать: у возврата он расходный.
     *
     * Своих статей у возврата нет и быть не должно: возвращают за трату, и
     * названа она уже — «Еда», «Транспорт». Заведи возврат свой словарь — и
     * та же «Еда» существовала бы в книге дважды, а вычесть одну из другой
     * стало бы нельзя.
     */
    val categoryKind: EntryKind get() = if (this == BACK) SPEND else this
}

/**
 * Что за счёт.
 *
 * Пять видов, и они не про банк, а про то, как к деньгам относятся: наличные
 * тратят, на карте держат, накопления не трогают, долг отдают, кредитную карту
 * гасят. Вид ничего не считает по-особому — он подсказывает знак, вопрос в
 * карточке и порядок в списке.
 *
 * Долг — такой же счёт, только уходит в минус: заняли — на счету минус,
 * отдали — ноль. Отдельной сущности «обязательство» с процентами и сроками
 * здесь нет: это уже не домашняя книга, а бухгалтерия предприятия.
 *
 * Кредитная карта — тот же долг, но с потолком: у неё есть лимит, и от него
 * считается, сколько ещё можно потратить. Отдельным видом, а не карточкой с
 * галочкой «кредитная», потому что спрашивают у неё другое: у обычной карты —
 * «сколько на ней лежит», у кредитной — «сколько вы уже должны».
 */
enum class AccountKind(val title: String) {
    CASH("Наличные"),
    CARD("Карта"),

    /**
     * Кредитная карта. Остаток на ней отрицательный и означает долг, а
     * [LedgerAccount.limit][app.askya.data.entity.LedgerAccount.limit] — тот
     * потолок, до которого банк даёт занимать.
     */
    CREDIT("Кредитная карта"),
    SAVINGS("Накопления"),
    DEBT("Долг"),
    ;

    /**
     * Счёт, на котором не лежат, а должны.
     *
     * Таких два, и в карточке они спрашивают не «сколько было», а «сколько
     * должны»: минус в поле суммы человек не набирает, а «долг в −20 000» —
     * это два отрицания на одно число.
     */
    val owed: Boolean get() = this == CREDIT || this == DEBT
}

/** Знак валюты. Одно место на всё приложение — см. рассуждение выше. */
const val RUBLE = "₽"

/**
 * Копейки — рублями, как их пишут: «1 234,50 ₽», «84 300 ₽».
 *
 * Копейки показываются, только если они есть: в книге, где почти все суммы
 * круглые, хвост «,00» у каждой строки читать мешает, а не помогает.
 *
 * Тысячи отбиты неразрывным пробелом — тем же, каким их отбивают в русском
 * письме, и разрывать число на конце строки он не даёт. Им же отбит и знак
 * рубля: «300» на одной строке и «₽» на другой — это не сумма, а опечатка.
 *
 * Минус — типографский, а не дефис: он одной ширины с цифрами, и столбец сумм
 * от него не разъезжается.
 */
fun formatMoney(kopecks: Long, withSign: Boolean = false): String {
    val minus = kopecks < 0
    val whole = Math.abs(kopecks) / 100
    val rest = (Math.abs(kopecks) % 100).toInt()

    val digits = whole.toString()
    val grouped = StringBuilder()
    digits.forEachIndexed { index, char ->
        if (index > 0 && (digits.length - index) % 3 == 0) grouped.append(' ')
        grouped.append(char)
    }
    if (rest != 0) grouped.append(',').append("%02d".format(rest))

    val sign = when {
        minus -> "−"
        withSign && kopecks > 0 -> "+"
        else -> ""
    }
    return "$sign$grouped $RUBLE"
}

/** То же, но пусто вместо нуля: в строке, где сумма не важна, ноль — шум. */
fun formatMoneyOrBlank(kopecks: Long): String = if (kopecks == 0L) "" else formatMoney(kopecks)

/**
 * Написанное — в копейки: «1 234,5» → 123450, «300» → 30000.
 *
 * Запятая и точка считаются одним и тем же: на телефоне под рукой то одна, то
 * другая, и требовать «правильную» — придирка. Всё, что не цифра и не
 * разделитель, отбрасывается: сумму вводят вместе со знаком рубля и с
 * пробелами чаще, чем кажется.
 *
 * Дробная часть режется до двух знаков, а не округляется: «12,345» — это не
 * сумма, это описка, и додумывать за человека третий знак незачем.
 *
 * `null` означает «числа не написано»: пустая строка — не ноль, а «ещё не
 * ввели», и записывать по ней трату в ноль рублей нельзя.
 */
fun parseMoney(raw: String): Long? {
    val clean = raw.replace(',', '.').filter { it.isDigit() || it == '.' }
    if (clean.none { it.isDigit() }) return null

    val whole = clean.substringBefore('.').ifEmpty { "0" }
    val fraction = clean.substringAfter('.', "").filter { it.isDigit() }.take(2).padEnd(2, '0')

    val rubles = whole.toLongOrNull() ?: return null
    // Потолок в сто миллиардов копеек — это миллиард рублей: дальше начинается
    // не домашняя книга, а описка в двадцать нулей.
    if (rubles > 1_000_000_000L) return null
    return rubles * 100 + fraction.toLong()
}

/** Копейки — обратно в строку для правки: «1234,50» → «1234,5». Ноль — пусто. */
fun moneyToText(kopecks: Long): String {
    if (kopecks == 0L) return ""
    val whole = kopecks / 100
    val rest = (kopecks % 100).toInt()
    return when {
        rest == 0 -> "$whole"
        rest % 10 == 0 -> "$whole,${rest / 10}"
        else -> "$whole,%02d".format(rest)
    }
}

/**
 * Какую часть предела съели: 0 — ничего, 1 — впритык, больше 1 — вышли за
 * него. Нет предела — нет и доли: полоску рисовать не от чего.
 */
fun limitShare(spent: Long, limit: Long): Float? {
    if (limit <= 0) return null
    return (spent.toDouble() / limit.toDouble()).toFloat()
}

/**
 * Долг по счёту — то же число, что и остаток, но с человеческим знаком.
 *
 * На кредитной карте остаток отрицательный: потратил тысячу — на счету минус
 * тысяча. Спрашивают же про неё не «сколько у меня на карте», а «сколько я
 * должен», и отвечать на это минусом значит заставлять читать знак вслух.
 * Плюсовой остаток (переплатили, положили своих) долгом не считается: должны
 * тогда не вы.
 */
fun debtOf(amount: Long): Long = if (amount < 0) -amount else 0

/**
 * Сколько ещё можно потратить по кредитной карте: лимит минус долг.
 *
 * `null` — лимит не записан, и считать не от чего. Бывает и отрицательным —
 * вышли за лимит; врать про «доступно 0» в этом случае не следует, потому что
 * ноль и перерасход — разные новости.
 */
fun creditLeft(limit: Long, amount: Long): Long? {
    if (limit <= 0) return null
    return limit - debtOf(amount)
}
