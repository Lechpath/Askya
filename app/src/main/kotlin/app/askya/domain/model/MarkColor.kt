package app.askya.domain.model

/**
 * Краска-метка — то, чем вещь узнают в лицо раньше, чем прочитают название.
 *
 * Восемь красок на всё приложение: ими покрашены корешки книг в Scroll и ими
 * же помечены счета, карты и статьи в Ledger. Одна палитра, а не две похожих,
 * потому что вопрос у них один и тот же — «которая из них моя?» — и человек,
 * научившийся узнавать зелёное в одном разделе, не должен переучиваться в
 * другом. Прежде она называлась BookColor и жила ради одних книг; книги от
 * переименования ничего не потеряли.
 *
 * Выбирается руками. Пусто значит «не выбирали»: тогда краска выводится из
 * названия — полка и счета всё равно окрашены, и человек не обязан выбирать
 * цвет каждой заведённой вещи.
 *
 * Порядок здесь — порядок в палитре выбора: тёплые, потом холодные, потом
 * тёмные. Хранится имя константы, а не номер, поэтому порядок можно менять
 * дальше, не трогая уже выбранное.
 */
enum class MarkColor {
    CORAL,
    AMBER,
    ROSE,
    GREEN,
    BLUE,
    PLUM,
    BROWN,
    INK,
}
