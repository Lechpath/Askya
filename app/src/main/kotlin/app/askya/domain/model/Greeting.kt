package app.askya.domain.model

import java.time.LocalTime

/**
 * Приветствие на заставке — по времени суток, по-английски и не одно и то же.
 *
 * Английское здесь не по недосмотру: Askya — имя, а не слово, и на заставке
 * рядом с ним стоит та же речь, что в самом знаке приложения. Внутри разделов
 * всё по-русски; заставка — единственное место, где приложение здоровается.
 *
 * ## Поры суток
 *
 * Границы взяты по человеческому дню, а не по четвертям суток: в пять утра
 * уже утро, а «Good night» в десять вечера — ещё пожелание, а не прощание.
 *
 * | с | до | пора |
 * |---|----|------|
 * | 05:00 | 11:59 | [Part.MORNING] |
 * | 12:00 | 16:59 | [Part.AFTERNOON] |
 * | 17:00 | 21:59 | [Part.EVENING] |
 * | 22:00 | 04:59 | [Part.NIGHT] |
 *
 * Это те же границы, что были у приложения с самого начала, — менялось не
 * расписание, а то, что в эти часы говорится.
 *
 * ## Правило чередования
 *
 * У каждой поры свой набор фраз, и первой в нём всегда стоит само приветствие
 * («Good morning»). Оно не должно потеряться среди прибауток: человек,
 * открывший приложение в первый раз, должен услышать приветствие, а не вопрос
 * про кофе.
 *
 * Дальше набор перебирается по кругу — по счётчику [turn], который приложение
 * увеличивает на каждом запуске (`SettingsPreferences.advanceGreeting`).
 * Счётчик один на все поры, а не свой у каждой: свои счётчики значили бы, что
 * утренний набор двигается только по утрам, и человек, открывающий Askya раз в
 * день, годами слышал бы одно и то же второе утро подряд. С общим счётчиком
 * фраза меняется от запуска к запуску, а внутри одной поры набор всё равно
 * перебирается целиком, ни одну не пропуская.
 *
 * Случайного выбора здесь нет намеренно: случайность повторяется — две одинаковые
 * фразы подряд человек читает как сбой, а не как совпадение. Перебор по кругу
 * не повторяется никогда.
 *
 * Фразы короткие и обращены к человеку, а не к экрану: это первое, что
 * приложение говорит за день, и длинное на этом месте читалось бы как реклама.
 */
object Greeting {

    /** Пора суток — своя, не [app.askya.ui.components.DayPart] расписания. */
    enum class Part {
        MORNING,
        AFTERNOON,
        EVENING,
        NIGHT,
    }

    /**
     * Утро: кофе, начало работы и вопрос о настроении.
     *
     * Утром человек ещё не в делах, и звать его в дела рано — сперва с ним
     * здороваются.
     */
    private val MORNING = listOf(
        "Good morning",
        "Coffee first?",
        "Ready for the workday?",
        "How's the mood?",
        "One cup, then the day",
        "Morning. Take it slow.",
        "The day is still empty",
    )

    /**
     * День: что дальше, записать, музыка, отдых.
     *
     * Днём человек уже внутри дел, и приветствие превращается в короткое
     * напоминание — то самое, ради чего заведена Askya.
     */
    private val AFTERNOON = listOf(
        "Good afternoon",
        "Let's see what's next",
        "Worth writing down?",
        "Some music?",
        "Save some time to rest",
        "Half the day is behind",
        "Anything you forgot?",
    )

    /**
     * Вечер: пора отдохнуть, что осталось, Claude Code.
     *
     * Вечером приложение не подгоняет: оно спрашивает, много ли осталось, и
     * тем самым разрешает закончить.
     */
    private val EVENING = listOf(
        "Good evening",
        "Time to slow down",
        "What's left for tonight?",
        "Maybe Claude Code?",
        "The day can end now",
        "Anything still open?",
        "Evening is yours",
    )

    /**
     * Ночь: ничего не начинать.
     *
     * Ночью приложение не предлагает дел вовсе — ни записать, ни послушать:
     * открывший Askya в час ночи пришёл не за планом на завтра.
     */
    private val NIGHT = listOf(
        "Good night",
        "Still up?",
        "Tomorrow can wait",
        "Last note of the day?",
        "Lights out soon",
        "Quiet hours",
    )

    /** Пора суток по часам. */
    fun partOf(time: LocalTime): Part = when (time.hour) {
        in 5..11 -> Part.MORNING
        in 12..16 -> Part.AFTERNOON
        in 17..21 -> Part.EVENING
        else -> Part.NIGHT
    }

    /** Весь набор поры — по порядку перебора. Первой стоит само приветствие. */
    fun phrases(part: Part): List<String> = when (part) {
        Part.MORNING -> MORNING
        Part.AFTERNOON -> AFTERNOON
        Part.EVENING -> EVENING
        Part.NIGHT -> NIGHT
    }

    /**
     * Что говорится в это время на этом обороте счётчика.
     *
     * [turn] считается по запускам приложения и растёт без конца; отрицательный
     * (какого быть не должно, но счётчик переживает и переполнение) сводится к
     * началу набора, а не роняет заставку.
     */
    fun of(time: LocalTime, turn: Int = 0): String {
        val pool = phrases(partOf(time))
        val index = ((turn % pool.size) + pool.size) % pool.size
        return pool[index]
    }

    /** Приветствие на сейчас. Часы спрашиваются в момент показа заставки. */
    fun now(turn: Int = 0): String = of(LocalTime.now(), turn)
}
