package app.askya.domain.model

import java.time.LocalTime

/**
 * Когда напомнить о деле: в названный час или за столько-то минут до начала.
 *
 * Два способа, а не один: «в восемь» и «за пятнадцать минут» — две разные
 * мысли. Свести вторую к первой пришлось бы человеку в уме, и заново при
 * каждом переносе дела: сдвинулось начало — сдвинулось и напоминание, если
 * оно сказано промежутком, и осталось на месте, если названо часом.
 */
sealed interface RemindAt {

    /** Названный час: напомнить в 19:00. */
    data class Exact(val time: LocalTime) : RemindAt

    /** Промежуток до начала: напомнить за 15 минут. */
    data class Before(val minutes: Int) : RemindAt
}
