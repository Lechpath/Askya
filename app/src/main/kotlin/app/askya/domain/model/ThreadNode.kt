package app.askya.domain.model

import java.time.LocalDate

/**
 * Узел нити — то, из чего сплетается замысел.
 *
 * ## Зачем нити своё содержимое, если раньше его нарочно не было
 *
 * Нить задумывалась как вопрос «как оно идёт», заданный поперёк разделов: дела
 * лежат в дне, траты в книге, строки в списках, а нить их собирает и ничего не
 * хранит. Это верно ровно до той минуты, пока замысел уже есть.
 *
 * А до неё — нет. «Хочу сделать альбом» это ещё не дела и не траты: это искра,
 * из которой сперва растут вопросы, возможные пути и понимание, чего вообще
 * хочется. Разложить такое по существующим разделам нельзя: в расписании ему
 * нет дня, в списке Yet оно становится задачей, которой никто не ставил, а в
 * записи Scroll — текстом, в котором через месяц не видно, что из чего выросло.
 *
 * Поэтому у нити появилось второе дно: карта замысла. Она не отменяет первого —
 * пульс, дела и траты остались на месте, — а стоит **до** него: сначала мысль
 * развивается, и только потом её часть превращается в дела дня.
 *
 * ## Почему типы, а не просто карточки
 *
 * Потому что человек и так думает разными вещами: одно — желание, другое —
 * способ до него добраться, третье — то, что мешает. Свалив их в одинаковые
 * прямоугольники, карта превращается в кучу текста, где всё весит одинаково.
 * Тип узла — это не украшение и не папка: он меняет и вид карточки, и вопрос,
 * который она задаёт, и то, что предлагается вырастить из неё дальше.
 *
 * Значком и формой, а не картинкой-смайликом: во всей Askya нет ни одного
 * эмодзи, и заводить их ради одного раздела значило бы притащить чужой шрифт,
 * который на каждом телефоне выглядит по-своему.
 */
enum class ThreadNodeKind(
    /** Как тип зовут человеку. */
    val title: String,
    /** Что в узле пишут — стоит подсказкой в пустом поле. */
    val hint: String,
    /**
     * Встречный вопрос: то, что карточка спрашивает, когда её открыли.
     *
     * Это и есть вся «помощь в размышлении», какая бывает без сети и без
     * модели: не совет, что делать, а вопрос, который человек, скорее всего,
     * задал бы себе сам, если бы вспомнил. Вопрос один и тот же у всех узлов
     * этого типа — и пусть: он не притворяется умным, он напоминает.
     */
    val nudge: String,
    /** Насколько крупно узел стоит на карте. */
    val size: NodeSize,
    /** Каким его видно с первого взгляда. */
    val shape: NodeShape,
) {
    SPARK(
        title = "Искра",
        hint = "Хочу сделать музыкальный альбом",
        nudge = "Что в этом зацепило? Часто настоящая искра рядом, а не в самих словах.",
        size = NodeSize.BIG,
        shape = NodeShape.ROUND,
    ),

    QUESTION(
        title = "Вопрос",
        hint = "А что если делать это вдвоём?",
        nudge = "Ответ на него что-нибудь меняет? Если нет — это ещё не тот вопрос.",
        size = NodeSize.SMALL,
        shape = NodeShape.ROUND,
    ),

    THOUGHT(
        title = "Мысль",
        hint = "Кажется, дело не в песнях, а в порядке",
        nudge = "Из этой мысли уже виден путь — или пока только направление?",
        size = NodeSize.PLAIN,
        shape = NodeShape.SOFT,
    ),

    RESULT(
        title = "Результат",
        hint = "Готовый альбом, который можно послушать целиком",
        nudge = "Что должно появиться в реальности, чтобы стало ясно: замысел состоялся?",
        size = NodeSize.BIG,
        shape = NodeShape.SOFT,
    ),

    PATH(
        title = "Путь",
        hint = "Начать с одной центральной песни",
        nudge = "Чем этот путь лучше соседнего? И что будет, если пойти обоими сразу?",
        size = NodeSize.PLAIN,
        shape = NodeShape.SOFT,
    ),

    SNAG(
        title = "Подводный камень",
        hint = "Нет времени на большой проект",
        nudge = "А если сделать так, чтобы этот камень перестал мешать? Что тогда выйдет?",
        size = NodeSize.PLAIN,
        shape = NodeShape.CUT,
    ),

    STEP(
        title = "Шаг",
        hint = "Записать черновик на телефон",
        nudge = "Он правда двигает нить — или это работа ради ощущения работы?",
        size = NodeSize.SMALL,
        shape = NodeShape.SHARP,
    ),

    INSIGHT(
        title = "Открытие",
        hint = "Понял: мешает не нехватка времени, а начало с нуля каждый раз",
        nudge = "Что в замысле теперь неверно? Открытие обычно что-нибудь отменяет.",
        size = NodeSize.PLAIN,
        shape = NodeShape.ROUND,
    ),

    TURN(
        title = "Поворот",
        hint = "Это не альбом, а один длинный трек",
        nudge = "Прежний результат ещё нужен — или его пора переписать?",
        size = NodeSize.BIG,
        shape = NodeShape.CUT,
    ),
    ;

    /**
     * Что обычно вырастает из узла этого типа — первым делом.
     *
     * Не правило и не проверка: вырастить можно что угодно, порядок лишь
     * ставит вперёд то, чем человек в этом месте продолжает чаще. Из
     * подводного камня первым предлагается **вопрос**, а не путь — потому что
     * препятствие, на которое сразу отвечают решением, отвечают старым; и
     * ровно тем же рассуждением из шага первым растёт открытие: шаг ценен
     * тем, что после него становится видно.
     */
    val grows: List<ThreadNodeKind>
        get() = when (this) {
            SPARK -> listOf(QUESTION, RESULT, THOUGHT)
            QUESTION -> listOf(THOUGHT, PATH, RESULT)
            THOUGHT -> listOf(PATH, QUESTION, RESULT)
            RESULT -> listOf(PATH, SNAG, STEP)
            PATH -> listOf(STEP, SNAG, THOUGHT)
            SNAG -> listOf(QUESTION, PATH, THOUGHT)
            STEP -> listOf(INSIGHT, SNAG, STEP)
            INSIGHT -> listOf(TURN, PATH, RESULT)
            TURN -> listOf(RESULT, PATH, QUESTION)
        }

    /**
     * Отмечается ли такой узел сделанным.
     *
     * Шаг — да: он либо сделан, либо нет. Результат — да, и это главная
     * отметка раздела: «замысел состоялся». Мысли, вопросу и повороту отметки
     * не полагается: их не делают, они случаются.
     */
    val markable: Boolean get() = this == STEP || this == RESULT

    companion object {
        /** Из строки в базе. Неизвестное — мысль: см. [ThreadState.of]. */
        fun of(name: String?): ThreadNodeKind = entries.firstOrNull { it.name == name } ?: THOUGHT
    }
}

/**
 * Насколько узел велик на карте.
 *
 * Размер здесь — не «важность» и не оценка: он говорит, сколько места вещь
 * занимает в замысле. Искра, результат и поворот держат карту, поэтому они
 * крупные; шаг и вопрос мелкие, потому что их бывает по десятку. Мерка в
 * пикселях лежит в разметке, а не тут: домен не должен знать про dp.
 */
enum class NodeSize { SMALL, PLAIN, BIG }

/**
 * Каким узел видно с первого взгляда.
 *
 * Форма нужна, чтобы тип читался раньше слов и на отдалении, когда карту
 * отодвинули и подписи стали в волосок. Круглое — то, что случилось само:
 * искра, вопрос, открытие. Мягкое — то, что человек придумал: мысль,
 * результат, путь. Срезанный угол — то, что ломает ход: камень и поворот.
 * Острое — шаг, единственное, что делается руками.
 */
enum class NodeShape { ROUND, SOFT, CUT, SHARP }

/**
 * Место на карте. Единица — та же, в которой рисуется карта, начало — там, где
 * стоит первый узел; отрицательные значения обычны: замысел растёт во все
 * стороны.
 */
data class Spot(val x: Float, val y: Float)

/** Шаг сетки: на столько отходит новый узел от того, из которого вырос. */
const val NODE_STEP = 168f

/** Ближе этого два узла не ставятся — иначе карточки налезают друг на друга. */
const val NODE_GAP = 132f

/**
 * Куда положить новый узел.
 *
 * Раскладывать карту руками человек не обязан — и особенно в ту секунду, когда
 * у него в голове мысль, которую он пришёл записать. Поэтому узел встаёт сам:
 * рядом с тем, из которого вырос, на первом свободном месте.
 *
 * Свободное ищется кольцами вокруг родителя: сперва вниз (замысел читается
 * сверху вниз, как всё написанное), потом вниз-вбок, потом вбок, и лишь потом
 * вверх. Кольцо расширяется, пока место не найдётся; шесть колец — это уже
 * полторы тысячи единиц во все стороны, дальше искать бессмысленно, и узел
 * ложится куда придётся: пусть лучше налезет, чем пропадёт.
 *
 * Первый узел нити встаёт в начало координат. Не в середину экрана: экраны
 * разные, а карта одна, и её начало не должно зависеть от того, с какого
 * телефона её завели.
 */
fun placeNear(parent: Spot?, taken: List<Spot>, step: Float = NODE_STEP): Spot {
    if (parent == null && taken.isEmpty()) return Spot(0f, 0f)

    // Узел без родителя — отдельная ветка замысла: она встаёт под всем, что уже
    // есть, а не в гуще. Иначе новая мысль немедленно теряется среди старых.
    val from = parent ?: Spot(
        x = taken.minOf { it.x },
        y = taken.maxOf { it.y },
    )

    for (ring in 1..6) {
        for (way in WAYS) {
            val spot = Spot(from.x + way.x * step * ring, from.y + way.y * step * ring)
            if (taken.none { near(it, spot) }) return spot
        }
    }
    return Spot(from.x, from.y + step * 7)
}

/** Заняты ли два места одним и тем же куском карты. */
private fun near(a: Spot, b: Spot): Boolean =
    kotlin.math.abs(a.x - b.x) < NODE_GAP && kotlin.math.abs(a.y - b.y) < NODE_GAP

/**
 * Стороны, в которые отходит новый узел, по порядку предпочтения.
 *
 * Вниз, вниз-вправо, вниз-влево — и только потом вбок и вверх: карта читается
 * сверху вниз, и выросшее из узла должно оказаться под ним, а не над.
 */
private val WAYS = listOf(
    Spot(0f, 1f),
    Spot(0.85f, 0.85f),
    Spot(-0.85f, 0.85f),
    Spot(1f, 0f),
    Spot(-1f, 0f),
    Spot(0.85f, -0.85f),
    Spot(-0.85f, -0.85f),
    Spot(0f, -1f),
)

/**
 * Признаки, по которым видно, что с нитью происходит.
 *
 * Считаются по самой карте и ни у кого не спрашиваются. Их четыре, и они
 * нарочно грубые: приложение не берётся знать, горит ли у человека внутри, —
 * оно знает только то, что записано.
 */
data class ThreadSigns(
    /** Сколько всего узлов. */
    val nodes: Int = 0,
    /** Сколько появилось за последние две недели. */
    val fresh: Int = 0,
    /** Сколько связей между узлами. */
    val ties: Int = 0,
    /** Сколько узлов, из которых расходится больше одной ветки. */
    val branches: Int = 0,
)

/** Свежим считается узел не старше этого срока. */
const val FRESH_DAYS = 14L

/** Связь, какой её видит счёт: два номера и ничего больше. */
data class Tie(val from: Long, val to: Long)

/**
 * Признаки нити по её карте.
 *
 * Принимает голые даты и пары номеров, а не строки таблиц: тогда счёт
 * проверяется тестом без базы — то же правило, что у [pulseOf] и [winsOf].
 *
 * Ветвление считается по узлам, **из** которых выходит больше одной связи:
 * замысел, у которого от результата тянется три пути, плетётся, а тот, у
 * которого узлы выстроены в цепочку, — растёт в длину, и это разные вещи.
 */
fun signsOf(made: List<LocalDate>, ties: List<Tie>, today: LocalDate): ThreadSigns =
    ThreadSigns(
        nodes = made.size,
        fresh = made.count { !it.isBefore(today.minusDays(FRESH_DAYS)) },
        ties = ties.size,
        branches = ties.groupBy { it.from }.count { it.value.size > 1 },
    )

/**
 * Пути, выросшие прямо из подводного камня, — обходы.
 *
 * Ровно они и весят больше обычного в списке побед: препятствие, ставшее
 * дорогой, — это то, ради чего в разделе вообще заведены камни.
 */
fun snagWays(kinds: Map<Long, ThreadNodeKind>, ties: List<Tie>): Set<Long> = ties
    .filter { kinds[it.from] == ThreadNodeKind.SNAG && kinds[it.to] == ThreadNodeKind.PATH }
    .map { it.to }
    .toSet()

/**
 * Что, судя по карте, с нитью сейчас — или `null`, если сказать нечего.
 *
 * Приложение не переставляет состояние само: оно предлагает, а человек
 * соглашается или нет. Разница не в вежливости — состояние нити это его
 * отношение к замыслу, а не счёт узлов, и приложение, которое переписывает
 * отношение человека по своим четырём признакам, врёт ему в лицо.
 *
 * Что видно с карты:
 *
 * - долгая тишина — «тлеет»: интерес не объявлен пропавшим, но и движения нет;
 * - свежие узлы и вчерашнее касание — «горит»;
 * - несколько ветвей и связей между ними — «плетётся»: замысел набирает
 *   структуру, а не просто прибавляет в длину;
 * - новые узлы без ветвления — «растёт».
 *
 * У спящей нити не спрашивают ничего: её отложили нарочно, и напоминать
 * человеку о его же решении — это и есть то самое канючанье, которого в Askya
 * нет. У закрытой тем более.
 *
 * Совпало с нынешним состоянием — `null`: сказать «похоже, она растёт» той,
 * что и так растёт, значит сказать пустое.
 */
fun suggestState(
    state: ThreadState,
    pulse: ThreadPulse,
    signs: ThreadSigns,
    today: LocalDate,
): ThreadState? {
    if (state.closed || state == ThreadState.SLEEPING) return null
    if (signs.nodes == 0) return null

    val silence = pulse.silence(today) ?: return null

    val guess = when {
        silence >= SILENT_DAYS -> ThreadState.SMOULDERING
        signs.fresh >= 2 && silence <= 3 -> ThreadState.BURNING
        signs.branches >= 2 && signs.ties >= 3 -> ThreadState.WEAVING
        signs.fresh >= 1 -> ThreadState.GROWING
        else -> return null
    }
    return guess.takeIf { it != state }
}

/**
 * Вес победы: не очки, а то, насколько сильно она сдвинула замысел.
 *
 * Очков в Askya нет и не будет — ни здесь, ни в «Прожитом». Вес нужен для
 * другого: чтобы список побед не превратился в ленту одинаковых галочек, где
 * «купил струны» стоит вровень с «понял, что это вообще не про альбом».
 */
enum class WinWeight { SMALL, REAL, BIG }

/** Победа: что случилось, какого веса и когда. */
data class ThreadWin(
    val nodeId: Long,
    val kind: ThreadNodeKind,
    val title: String,
    val weight: WinWeight,
    val at: LocalDate,
)

/**
 * Что в нити засчитывается победой.
 *
 * Сделанный шаг — маленькая: он и есть та самая маленькая победа, ради
 * которой всё затевалось. Открытие — настоящая: оно меняет то, что человек
 * знает о замысле. Поворот и достигнутый результат — большие: после них
 * замысел уже другой.
 *
 * И отдельно — **путь, выросший из подводного камня**: способ обойти то, что
 * мешало. Такой путь весит больше обычного, потому что он и есть то, ради чего
 * в разделе вообще заведены камни: препятствие, ставшее дорогой.
 *
 * Считается по карте, ничего не хранит и ничем не награждает: список побед —
 * это память о том, как замысел двигался, а не табло.
 */
fun winsOf(
    nodes: List<ThreadNodeFact>,
    tiedToSnag: Set<Long> = emptySet(),
): List<ThreadWin> = nodes.mapNotNull { node ->
    val weight = when {
        node.kind == ThreadNodeKind.TURN -> WinWeight.BIG
        node.kind == ThreadNodeKind.RESULT && node.doneOn != null -> WinWeight.BIG
        node.kind == ThreadNodeKind.INSIGHT -> WinWeight.REAL
        node.kind == ThreadNodeKind.PATH && node.id in tiedToSnag -> WinWeight.REAL
        node.kind == ThreadNodeKind.STEP && node.doneOn != null -> WinWeight.SMALL
        else -> null
    } ?: return@mapNotNull null

    ThreadWin(
        nodeId = node.id,
        kind = node.kind,
        title = node.title,
        weight = weight,
        at = node.doneOn ?: node.madeOn,
    )
}.sortedByDescending { it.at }

/**
 * Узел, каким его видит счёт побед: без места на карте и без текста.
 *
 * Отдельным видом, а не строкой таблицы, чтобы [winsOf] можно было проверить
 * тестом, не заводя базы, — то же рассуждение, что у [pulseOf].
 */
data class ThreadNodeFact(
    val id: Long,
    val kind: ThreadNodeKind,
    val title: String,
    val madeOn: LocalDate,
    val doneOn: LocalDate? = null,
)
