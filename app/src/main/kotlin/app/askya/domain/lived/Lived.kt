package app.askya.domain.lived

import java.time.LocalDate

/**
 * «Прожитое» — счёт по делам, за которыми человек следит.
 *
 * ## Зачем
 *
 * Календарь ставил точку под занятым днём, и это всё, что приложение говорило о
 * прошлом. При этом в базе лежит то, чего нет ни у одного планировщика: какие
 * дела человек **ставил** и какие **отмечал сделанными**, день за днём,
 * несколько лет подряд. Разница между первым и вторым — самая честная вещь,
 * которую можно сказать человеку о его годе.
 *
 * ## Почему только выбранное
 *
 * Раздел начинался с общего счёта: полоса всего года, самый занятый месяц,
 * «записано 222 дела, отмечено 135». Всё это правда и всё это ни о чём: сумма
 * по «Завтраку», «Отвезти Алёну» и «Чтению Библии» не отвечает ни на один
 * вопрос, который человек себе задаёт. А задаёт он вопросы точные — «как часто
 * я читаю Библию», «сколько раз я собирался бегать и сколько раз побежал», — и
 * ответ на них нельзя получить, выбирая самое яркое за него.
 *
 * Потому считается ровно то, что человек отметил сам, и ничего сверх. Целей,
 * очков и «привычек» здесь тоже нет: дело уже есть в дне, у него уже есть
 * отметка, и всё, о чём просят, — вести ему счёт.
 *
 * ## Почему чистые правила
 *
 * Всё, что здесь считается, — обычный SQL и обычная арифметика, и всё покрыто
 * тестами. На телефоне их не проверить: чтобы увидеть «24 дня подряд», нужен
 * год записей, а чтобы поймать ошибку в счёте — второй такой же год с известным
 * ответом.
 */
data class LivedRow(val title: String, val date: LocalDate, val done: Boolean)

// ——— Слова ———

internal fun dayWord(value: Int) = plural(value, "день", "дня", "дней")

internal fun timesWord(value: Int) = plural(value, "раз", "раза", "раз")

/** Русский счёт: один раз, два раза, пять раз. */
internal fun plural(value: Int, one: String, few: String, many: String): String {
    val tail = value % 100
    if (tail in 11..14) return many
    return when (value % 10) {
        1 -> one
        2, 3, 4 -> few
        else -> many
    }
}
