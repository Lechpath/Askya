package app.askya.domain.plan

import java.time.LocalTime

/**
 * Одно и то же дело, встретившееся в списке дважды: остаётся то, что раньше.
 *
 * Список дел человек ведёт руками и годами, и одно и то же дело заводится в
 * нём по второму разу — «Зарядка» в семь и «Зарядка» в половине девятого,
 * «Прогулка» утром и «Прогулка» же вечером, оставшаяся от прошлой зимы.
 * Развёрнутые в день, они дают два одинаковых блока, между которыми нечего
 * выбирать: названы они одинаково, и отличить их можно только по часу.
 *
 * Поэтому выбирает Askya, и выбирает раннее. Не потому, что раннее лучше, а
 * потому, что день собирается **вперёд**: то, что стоит первым, ещё можно
 * сделать, а то, что позже, — уже нет, если день начался. Правило должно быть
 * одно и всегда одно; «которое из двух» — не тот вопрос, который стоит
 * задавать каждое утро.
 *
 * Одинаковыми считаются дела с совпавшим названием **или** с совпавшим
 * описанием: название человек правит («Бег» → «Бег 5 км»), а заметку под ним
 * оставляет прежней, и по ней дело узнаётся тогда, когда по названию уже нет.
 * Пустые названия и пустые заметки друг с другом не сравниваются: пустота
 * ничего не говорит о том, то же это дело или другое.
 *
 * Сравнение — без учёта регистра и краевых пробелов: «зарядка» и «Зарядка »
 * набраны в разные дни одним и тем же человеком об одном и том же.
 *
 * Порядок на выходе — по времени: раскладывать день всё равно по нему.
 */
fun <T> keepEarliestOfSame(
    items: List<T>,
    at: (T) -> LocalTime,
    title: (T) -> String,
    note: (T) -> String = { "" },
): List<T> {
    val titles = HashSet<String>()
    val notes = HashSet<String>()

    // sortedBy устойчива: у дел, назначенных на один и тот же час, порядок
    // остаётся тем, в каком они лежали в списке, — и первым остаётся первое.
    return items.sortedBy(at).filter { item ->
        val name = title(item).trim().lowercase()
        val about = note(item).trim().lowercase()
        val seen = (name.isNotEmpty() && name in titles) || (about.isNotEmpty() && about in notes)
        if (!seen) {
            if (name.isNotEmpty()) titles += name
            if (about.isNotEmpty()) notes += about
        }
        !seen
    }
}
