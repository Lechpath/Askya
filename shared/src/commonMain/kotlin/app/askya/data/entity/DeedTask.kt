package app.askya.data.entity

import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey
import app.askya.data.sync.Uid
import java.time.LocalDateTime

/**
 * Строка списка внутри дела дня.
 *
 * ## Зачем она, если есть заметка и есть Yet
 *
 * Заметка у дела одна и сплошная: в неё пишут «взять пропуск, позвонить в
 * банк», и отметить в ней сделанное нельзя — можно только переписать строку.
 * Список Yet, наоборот, отмечается, но живёт своей жизнью: «ещё купить» не
 * принадлежит никакому часу и никакому дню.
 *
 * Между ними и стоит эта таблица: список, который принадлежит одному делу
 * одного дня. «Работа» с четырьмя задачами на сегодня — не заметка, потому что
 * задачи отмечают, и не список Yet, потому что завтрашняя работа будет другой.
 *
 * Привязка дела к списку Yet при этом никуда не делась
 * ([app.askya.domain.model.LinkKind.YET]) и остаётся тем же, чем была: делом
 * можно вести общий список, который переживает день. Здесь — про сегодня.
 *
 * ## Почему без внешнего ключа
 *
 * Как у строк Scroll и Yet: удаление дела убирает его строки явно, в
 * репозитории, а не каскадом из базы. Каскад пришлось бы объявлять и в Room, и
 * в SQLite, и он молча срабатывал бы на мягком удалении, которого дело как раз
 * и не переживает — убранное дело живёт сутки и возвращается со списком.
 *
 * Сделанное не исчезает, а уходит вниз — как в Yet: вычеркнутая строка это ещё
 * и память о том, что сделано.
 *
 * ## Заголовок — такая же строка, только без квадрата
 *
 * Список внутри дела оказался не одним списком. У поездки на объект в нём и
 * то, что там сделать, и то, что туда взять, и то, что купить по дороге, — три
 * разных перечня, которые человек всё равно пишет в одно дело, потому что дело
 * одно. Сваленные подряд, они читались кашей: «шуруповёрт» стоял между
 * «позвонить прорабу» и «замерить проём», и отличить взятое от сделанного
 * можно было только по памяти.
 *
 * Поэтому строка бывает заголовком ([heading]) — «Взять с собой», «Купить», —
 * и тогда у неё нет квадрата, её не отмечают и она не считается в «3 из 7».
 * Отдельной таблицы «разделов» для этого не завели: раздел — это та же строка
 * на том же месте, и всё, чем он отличается, здесь и написано.
 */
@Entity(tableName = "deed_tasks", indices = [Index("deedId"), Index("uid", unique = true)])
data class DeedTask(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    /**
     * Имя строки, общее для всех устройств, — см. [app.askya.data.sync.Uid].
     * Проставляется само и не меняется никогда: по нему строку узнают при
     * слиянии с другим устройством.
     */
    val uid: String = Uid.new(),
    val deedId: Long,
    val text: String = "",
    val done: Boolean = false,
    /**
     * Заголовок раздела, а не строка списка: «Взять с собой», «Купить».
     *
     * Пишется решёткой впереди — «# Взять с собой», — тем же знаком, каким
     * заголовок набирают в заметке. Разбирается при вводе
     * ([app.askya.data.repository.DeedTaskRepository.addLines]), а хранится
     * уже разобранным: в списке лежит написанное, а не то, чем его записали.
     */
    val heading: Boolean = false,
    val createdAt: LocalDateTime = LocalDateTime.now(),
    /**
     * Когда строку убрали. `null` — на месте.
     *
     * Мягкое удаление, как у дела, записи и строки Yet: подтверждение «вы
     * уверены?» не отменяет ошибку, оно перекладывает её на человека, который
     * торопится. Убранное живёт сутки, снизу появляется «Вернуть», и
     * подтверждений не нужно вовсе.
     */
    val removedAt: LocalDateTime? = null,
)
