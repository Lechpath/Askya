package app.askya.data.entity

import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey
import app.askya.data.sync.Uid
import app.askya.domain.model.BlockIcon
import app.askya.domain.model.DeedDays
import app.askya.domain.model.Priority
import java.time.DayOfWeek
import java.time.LocalDate
import java.time.LocalTime

/**
 * Дело обычного дня — то, из чего день состоит по умолчанию. Askya разворачивает
 * эти записи в расписание конкретной даты, а дальше день живёт своей жизнью:
 * правки в дне на распорядок не влияют и наоборот.
 *
 * [priority] решает, встаёт ли дело в день само: важное встаёт (см.
 * [standsAlone]). Раньше важность не значила ничего — она осталась от разбора
 * рассказа о себе, где решала, куда поставить дело без названного часа.
 *
 * [enabled] позволяет временно выключить дело, не теряя его формулировку.
 *
 * [icon] пуст почти всегда: знак угадывается по названию, а колонка хранит
 * только то, что человек выбрал руками вопреки догадке.
 *
 * [link] — чем это дело делается (см. [app.askya.domain.model.DeedLink]).
 * Привязка стоит и здесь, а не только у дела в дне, потому что повторяющееся
 * дело делается одним и тем же: сказав это один раз в списке, человек не
 * повторяет выбор в каждом дне.
 *
 * [days] — по каким дням недели дело повторяется (см. [DeedDays]). Пусто —
 * каждый день, и это же значение у всех дел, заведённых до появления колонки.
 */
@Entity(tableName = "routine_items", indices = [Index("uid", unique = true)])
data class RoutineItem(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    /**
     * Имя строки, общее для всех устройств, — см. [app.askya.data.sync.Uid].
     * Проставляется само и не меняется никогда: по нему строку узнают при
     * слиянии с другим устройством.
     */
    val uid: String = Uid.new(),
    val title: String,
    val startTime: LocalTime,
    val endTime: LocalTime? = null,
    val priority: Priority = Priority.NORMAL,
    val enabled: Boolean = true,
    val icon: BlockIcon? = null,
    val link: String? = null,
    val days: String? = null,
) {

    /** Дни недели дела разобранными. Пустой набор — каждый день. */
    val repeatDays: Set<DayOfWeek> get() = DeedDays.of(days)

    /**
     * Случается ли дело в эту дату.
     *
     * Спрашивает сборка дня и всё, что показывает список рядом с датой:
     * повторение — свойство самого дела, и разбирать колонку в каждом месте
     * заново значило бы получить два разных ответа об одном деле.
     */
    fun on(date: LocalDate): Boolean = DeedDays.on(repeatDays, date)

    /**
     * Встаёт ли дело в день само — не дожидаясь сборки.
     *
     * ## Зачем
     *
     * Список разворачивается в день целиком и один раз — при первом открытии
     * ([app.askya.data.repository.DayRepository.ensureComposed]), — и только
     * если человек не выключил заполнение дня. Для обычного дела так и надо:
     * тот, кто ведёт день руками, не должен каждое утро стирать развёрнутое.
     *
     * Но два дела из списка человек назвал не «вообще», а про конкретные дни,
     * и оба одинаково пропадали при выключенном заполнении:
     *
     * **Важное.** Пометив «Важно», человек сказал: об этом надо помнить
     * отдельно. Дело, о котором надо помнить отдельно, — ровно то, которое не
     * должно требовать ежедневного выбора из списка.
     *
     * **С выбранными днями.** «Пн Ср Пт» — это не «дело бывает», это «дело
     * будет в понедельник». Заводя такое, человек и заводит его затем, чтобы
     * в понедельник оно уже стояло; ставить его в понедельник руками — значит
     * вести те же дни второй раз.
     *
     * Дело «каждый день» сюда не входит: у него дней не выбирали — пустая
     * колонка досталась ему по умолчанию (см. [DeedDays]), и принять её за
     * просьбу про все семь дней значило бы развернуть весь список в обход
     * выключателя.
     */
    val standsAlone: Boolean
        get() = priority == Priority.HIGH || repeatDays.isNotEmpty()
}
