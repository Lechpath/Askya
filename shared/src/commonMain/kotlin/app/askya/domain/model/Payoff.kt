package app.askya.domain.model

import java.time.YearMonth
import kotlin.math.ceil
import kotlin.math.pow
import kotlin.math.roundToLong

/**
 * Как закрыть долг: сколько платить в месяц, чтобы к сроку не осталось ничего.
 *
 * ## Почему сроками, а не платежами
 *
 * Спрашивают всегда одно и то же: «за сколько я это закрою?» Ответ на него —
 * платёж, а не наоборот. Калькулятор, который просит ввести платёж и говорит
 * срок, заставляет подбирать число вслепую: набрал десять тысяч — двадцать
 * месяцев, набрал пятнадцать — четырнадцать, и так до тех пор, пока не сойдётся
 * с тем, что человек и без того знал про свои деньги. Шесть готовых сроков
 * ставят вопрос ребром: месяц, три, полгода, год, полтора, два — вот платёж и
 * вот переплата за каждый. Выбирают тот, который по карману.
 *
 * Шесть, а не ползунок с любым числом месяцев: между «за год» и «за
 * тринадцать месяцев» разницы для решения нет, а ползунок требует крутить его
 * до ответа. Дальше двух лет не считается: домашний долг, который гасят третий
 * год, — это разговор не с калькулятором.
 *
 * ## Аннуитет, потому что так считает банк
 *
 * Платёж считается по той же формуле, по какой его считает банк: равные
 * ежемесячные суммы, проценты начисляются на остаток. Делить долг на число
 * месяцев можно только при нулевой ставке — иначе за год набегут проценты,
 * которых в таком делении нет, и обещанный срок сдвинется.
 *
 * Платёж округляется вверх до копейки: округлённый вниз оставил бы хвост,
 * из-за которого последний месяц не закрыл бы долг. Из-за этого же последний
 * платёж обычно чуть меньше остальных — в [Payoff.total] это учтено, там
 * сложены настоящие платежи, а не платёж, умноженный на число месяцев.
 *
 * ## Чего здесь нет
 *
 * Беспроцентного периода, штрафов, страховок и комиссий: это условия
 * конкретного договора, и книга их не знает. Нулевая ставка означает ровно
 * «процентов не считаем» — и тогда план говорит про платёж и молчит про
 * переплату, вместо того чтобы называть её нулём.
 */
data class Payoff(
    val months: Int,
    /** Сколько платить каждый месяц, копейки. */
    val monthly: Long,
    /** Сколько отдадите всего: долг вместе с процентами. */
    val total: Long,
    /** Переплата процентами. Нулевая ставка — нулевая переплата. */
    val overpay: Long,
    /** Месяц последнего платежа. */
    val until: YearMonth,
)

/** Сроки, за которые предлагается закрыть долг. */
enum class PayoffTerm(val months: Int, val title: String) {
    MONTH(1, "За месяц"),
    QUARTER(3, "За три месяца"),
    HALF(6, "За полгода"),
    YEAR(12, "За год"),
    YEAR_AND_HALF(18, "За полтора года"),
    TWO_YEARS(24, "За два года"),
}

/**
 * План на один срок. `null` — долга нет и считать нечего.
 *
 * [rate] — годовая ставка в сотых долях процента: 24,9 % это 2490.
 */
fun payoff(
    debt: Long,
    rate: Int,
    months: Int,
    from: YearMonth = YearMonth.now(),
): Payoff? {
    if (debt <= 0 || months <= 0) return null

    // Месячная ставка: годовая, делённая на двенадцать. Именно так её делит и
    // банк — сложным процентом с точной капитализацией здесь никто не считает.
    val monthlyRate = rate / 120_000.0
    val monthly = if (monthlyRate <= 0.0) {
        ceilDiv(debt, months.toLong())
    } else {
        ceil(debt * monthlyRate / (1 - (1 + monthlyRate).pow(-months.toDouble()))).toLong()
    }

    // Настоящие платежи, а не платёж, умноженный на срок: последний месяц
    // закрывает остаток и почти всегда меньше прочих.
    var left = debt
    var paid = 0L
    repeat(months) {
        if (left <= 0) return@repeat
        val interest = (left * monthlyRate).roundToLong()
        val due = minOf(monthly, left + interest)
        paid += due
        left = left + interest - due
    }

    return Payoff(
        months = months,
        monthly = monthly,
        total = paid,
        overpay = paid - debt,
        until = from.plusMonths(months.toLong() - 1),
    )
}

/** Все шесть планов разом — в том порядке, в каком они стоят карточками. */
fun payoffPlans(debt: Long, rate: Int, from: YearMonth = YearMonth.now()): List<Payoff> =
    PayoffTerm.entries.mapNotNull { term -> payoff(debt, rate, term.months, from) }

/**
 * В каком порядке гасить, когда долгов несколько.
 *
 * Два способа, и спорят о них не первое десятилетие. **Лавина** сберегает
 * деньги: гасят тот, у которого ставка выше, и общая переплата выходит
 * наименьшей — это арифметика, и спорить с ней нечем. **Снежный ком** сберегает
 * решимость: гасят самый маленький, и первый долг закрывается через месяц-два,
 * а не через год. Считать выгоду он умеет хуже, а доводить до конца — лучше,
 * и это подтверждается не рассуждением, а тем, что люди чаще дохаживают до
 * конца именно по нему.
 *
 * Оба предлагаются, потому что выбор здесь не арифметический: одному нужна
 * экономия, другому — чтобы что-нибудь наконец закрылось.
 */
enum class PayoffOrder(val title: String, val about: String) {
    SNOWBALL(
        "Снежный ком",
        "Сначала самый маленький долг. Он закроется быстрее всех — и дальше " +
            "гасить будет легче, потому что видно, что это работает.",
    ),
    AVALANCHE(
        "Лавина",
        "Сначала тот, у которого ставка выше. Переплата выходит наименьшей, " +
            "но первый закрытый долг ждать дольше.",
    ),
}

/** Долг, каким его видит очередь: имя, сколько и под сколько. */
data class Debt(val id: Long, val title: String, val amount: Long, val rate: Int)

/**
 * Очередь долгов по выбранному способу.
 *
 * Смысл очереди один: по всем долгам платят минимум, а всё, что сверх него,
 * кладут на первый в очереди. Закрылся — тем же весом наваливаются на
 * следующий, отчего способ и назван снежным комом.
 *
 * Долги без остатка в очередь не попадают: гасить нечего.
 */
fun payoffQueue(debts: List<Debt>, order: PayoffOrder): List<Debt> {
    val owed = debts.filter { it.amount > 0 }
    return when (order) {
        // Внутри равных — меньший долг вперёд: из двух одинаково дорогих
        // раньше закроется тот, который меньше.
        PayoffOrder.AVALANCHE -> owed.sortedWith(compareByDescending<Debt> { it.rate }.thenBy { it.amount })
        PayoffOrder.SNOWBALL -> owed.sortedWith(compareBy<Debt> { it.amount }.thenByDescending { it.rate })
    }
}

/** Деление вверх: остаток в копейку иначе оставил бы долг незакрытым. */
private fun ceilDiv(value: Long, by: Long): Long = (value + by - 1) / by

/**
 * Ставка из написанного: «24,9» → 2490. `null` — числа не написано.
 *
 * Запятая и точка — одно и то же, как и в суммах. Тысяча процентов годовых —
 * потолок: выше начинается не ставка, а описка в лишний ноль.
 */
fun parseRate(raw: String): Int? {
    val clean = raw.replace(',', '.').filter { it.isDigit() || it == '.' }
    if (clean.none { it.isDigit() }) return null

    val whole = clean.substringBefore('.').ifEmpty { "0" }
    val fraction = clean.substringAfter('.', "").filter { it.isDigit() }.take(2).padEnd(2, '0')

    val percent = whole.toIntOrNull() ?: return null
    if (percent > 1_000) return null
    return percent * 100 + fraction.toInt()
}

/** Ставка обратно в строку для правки: 2490 → «24,9». Ноль — пусто. */
fun rateToText(rate: Int): String {
    if (rate <= 0) return ""
    val whole = rate / 100
    val rest = rate % 100
    return when {
        rest == 0 -> "$whole"
        rest % 10 == 0 -> "$whole,${rest / 10}"
        else -> "$whole,%02d".format(rest)
    }
}

/** Ставка как её пишут: «24,9 % годовых». Ноль — пусто. */
fun formatRate(rate: Int): String = if (rate <= 0) "" else "${rateToText(rate)} % годовых"
