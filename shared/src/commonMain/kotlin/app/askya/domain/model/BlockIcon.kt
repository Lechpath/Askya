package app.askya.domain.model

/**
 * Чем дело занимается — по этому в карточке выбирается знак.
 *
 * Порядок здесь — это порядок в палитре выбора: знаки идут не как попало, а
 * кучками по смыслу — утро и еда, работа и связь, дорога, дом, люди, отдых.
 * Искать глазами в такой сетке проще, чем в списке, собранном по алфавиту или
 * по времени добавления.
 *
 * По названию угадывается только часть из них ([BlockIcons]); остальные
 * существуют ради выбора руками — угадывать «подарок» или «кино» по слову
 * значит промахиваться чаще, чем попадать.
 *
 * Хранится имя константы, поэтому порядок можно менять и дальше: перестановка
 * не трогает уже выбранное.
 */
enum class BlockIcon {
    // Утро, тело, еда
    WAKE,
    SLEEP,
    SHOWER,
    FOOD,
    COFFEE,
    COOK,
    WATER,
    HEALTH,

    // Работа, учёба, связь
    WORK,
    CODE,
    STUDY,
    READ,
    WRITE,
    CALL,
    MAIL,
    CHAT,
    MONEY,

    // Дорога и движение
    ROAD,
    WALK,
    BIKE,
    FLIGHT,
    SPORT,

    // Дом
    HOUSE,
    CLEAN,
    LAUNDRY,
    REPAIR,
    SHOP,
    PLANT,

    // Люди
    MEET,
    CHILD,
    PETS,
    GIFT,
    SERVICE,

    // Отдых
    REST,
    MUSIC,
    MOVIE,
    GAME,
    PHOTO,
    NATURE,

    // Не угадалось и не выбрали
    PLAIN,
}

/**
 * Знак дела выводится из названия, а не спрашивается.
 *
 * Выбор иконки к каждому делу — это ещё одно поле в диалоге и ещё одно решение
 * на каждое дело; человек заводит дела на ходу и заполнять его не станет. По
 * названию угадывается почти всё: «Бег», «Дорога домой», «Чтение Библии»
 * говорят о себе сами. Поменять знак руками можно — тапом по нему в раскрытой
 * карточке, — но это ответ на промах догадки, а не обязательный шаг.
 *
 * Сравнивается начало слова, а не вхождение в строку. Иначе корень попадает
 * внутрь чужого слова: «жен» нашлось в «приложения», и дело про код оказалось
 * встречей с женой.
 *
 * Порядок правил важен: сначала узкие слова, потом общие. «Чтение Библии» — это
 * чтение, а не служение, хотя «Библия» встречается в обоих.
 *
 * Не угадалось — остаётся [BlockIcon.PLAIN], часы. Это честнее, чем подставить
 * случайный знак: неверная картинка врёт, а часы просто ничего не добавляют.
 */
object BlockIcons {

    private val RULES: List<Pair<BlockIcon, List<String>>> = listOf(
        BlockIcon.WAKE to listOf("подъём", "подъем", "просну", "будильник"),
        BlockIcon.SLEEP to listOf("сон", "спать", "отбой", "лечь"),
        BlockIcon.SHOWER to listOf("душ", "ванна", "гигиен", "зубы"),
        BlockIcon.FOOD to listOf("завтрак", "обед", "ужин", "еда", "еды", "перекус", "кофе", "чай"),
        BlockIcon.ROAD to listOf("дорог", "поездк", "ехать", "еду", "путь", "метро", "трансфер"),
        BlockIcon.SPORT to listOf("бег", "зарядк", "спорт", "трениров", "прогулк", "велос", "плаван"),
        BlockIcon.READ to listOf("чтение", "читать", "книг", "библи", "конспект"),
        BlockIcon.SERVICE to listOf("служение", "молитв", "собрание", "церк", "проповед"),
        BlockIcon.STUDY to listOf("учёба", "учеба", "курс", "урок", "лекц", "изучен", "разбор"),
        BlockIcon.CALL to listOf("звонок", "позвонить", "созвон", "телефон"),
        BlockIcon.SHOP to listOf("магазин", "купить", "покупк", "продукт", "рынок"),
        BlockIcon.HOUSE to listOf("уборк", "стирк", "готовк", "посуд", "ремонт", "дома"),
        BlockIcon.WORK to listOf("работ", "смена", "офис", "задач", "проект", "код"),
        // Корни, а не слова целиком: «Время с женой» — это «жен», а не «жена».
        BlockIcon.MEET to listOf("встреч", "гост", "жен", "муж", "семь", "друз", "дет", "родител"),
        BlockIcon.REST to listOf("отдых", "тишина", "восстановлен", "пауза", "медитац", "перерыв"),
    )

    fun of(title: String): BlockIcon {
        val words = title.lowercase().split(WORDS).filter { it.isNotEmpty() }
        RULES.forEach { (icon, keys) ->
            if (words.any { word -> keys.any(word::startsWith) }) return icon
        }
        return BlockIcon.PLAIN
    }

    /** Всё, что не буква и не цифра, считается границей слова. */
    private val WORDS = Regex("""[^\p{L}\p{N}]+""")
}
