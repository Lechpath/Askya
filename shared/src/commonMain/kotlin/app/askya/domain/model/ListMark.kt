package app.askya.domain.model

/**
 * Чем отмечается строка списка.
 *
 * Выбирается на весь список, а не на строку: список — это один перечень, и
 * разные знаки внутри него читались бы как разные сорта строк. Покупки удобно
 * отмечать квадратом, прочитанные книги — галочкой, а перечень, в котором
 * ничего не отмечают, живёт точкой.
 *
 * Пока не отмечено, знак серый; отмеченное — коралловое, как выполненное дело
 * в AskyaDay. Цвет один на все четыре вида: меняется форма, а не смысл.
 *
 * Хранится именем константы, а не номером, — как цвет корешка книги: порядок
 * тогда можно менять, не трогая уже заведённые списки.
 */
enum class ListMark {
    /** Квадрат с галочкой — тот же знак, что у чек-листа в заметке. */
    SQUARE,

    /** Кружок: заполняется, когда отмечено. */
    CIRCLE,

    /** Точка: перечень, в котором отмечают редко. */
    DOT,

    /** Одна галочка без рамки — легче всех остальных. */
    TICK,
}
