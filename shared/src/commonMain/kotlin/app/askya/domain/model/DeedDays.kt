package app.askya.domain.model

import java.time.DayOfWeek
import java.time.LocalDate

/**
 * По каким дням недели повторяется дело списка.
 *
 * ## Зачем
 *
 * Список дел до сих пор знал одно повторение — «каждый день»: всё, что в нём
 * записано, разворачивалось в любую дату. Но обычный день бывает разным по
 * дням недели, и повторяющееся дело чаще всего повторяется не ежедневно:
 * мусор выносят по вторникам и пятницам, в зал ходят через день, на встречу
 * собираются по воскресеньям. Заводить такое ежедневным значило бы каждый день
 * стирать из дня то, чего сегодня нет, — и тогда список перестают вести.
 *
 * ## Почему дни недели, а не «правило повторения»
 *
 * Ни «каждые N дней», ни «каждое пятое число», ни «второй вторник месяца».
 * Всё это правила календаря предприятия: их описывают строкой RRULE, показать
 * их человеку одной строкой нельзя, а спрашивают в домашнем списке почти
 * всегда одно — по каким дням недели. День недели ещё и виден глазом: «Пн Ср
 * Пт» читается сразу, а «каждые 2 дня» требует помнить, от какого числа
 * считать.
 *
 * Разовое дело на дату сюда не относится вовсе: оно записывается прямо в день
 * (AskyaDay, календарь), а список — про то, что повторяется.
 *
 * ## Пустой набор — это «каждый день»
 *
 * Не «ни в один». Так старые дела, записанные до появления колонки, остаются
 * ежедневными без единой строки переноса, а человек, не тронувший дни, получает
 * прежнее поведение. «Ни в один день» смысла не имеет: дело, которое не
 * случается никогда, выключают переключателем, а не пустым набором дней.
 */
object DeedDays {

    /** Все семь по порядку недели — с понедельника, как в календаре Askya. */
    val week: List<DayOfWeek> = listOf(
        DayOfWeek.MONDAY,
        DayOfWeek.TUESDAY,
        DayOfWeek.WEDNESDAY,
        DayOfWeek.THURSDAY,
        DayOfWeek.FRIDAY,
        DayOfWeek.SATURDAY,
        DayOfWeek.SUNDAY,
    )

    private val WORKDAYS = week.take(5).toSet()
    private val WEEKEND = week.drop(5).toSet()

    /**
     * Разобрать записанное: «1,3,5» — понедельник, среда, пятница.
     *
     * Числа те же, что в [DayOfWeek.getValue], — понедельник первый. Пусто,
     * мусор и числа не из недели дают пустой набор, то есть «каждый день»:
     * колонка, испорченная будущей версией, не должна отменять дело.
     */
    fun of(raw: String?): Set<DayOfWeek> {
        val text = raw?.trim().orEmpty()
        if (text.isEmpty()) return emptySet()
        val days = text.split(',')
            .mapNotNull { it.trim().toIntOrNull() }
            .filter { it in 1..7 }
            .map { DayOfWeek.of(it) }
            .toSet()
        return if (days.size == 7) emptySet() else days
    }

    /**
     * Как набор ложится в колонку. Пусто и все семь — `null`: и то и другое
     * значит «каждый день», и хранить их двумя разными строками значило бы
     * завести два вида одного и того же.
     */
    fun store(days: Set<DayOfWeek>): String? {
        if (days.isEmpty() || days.size == 7) return null
        return week.filter { it in days }.joinToString(",") { it.value.toString() }
    }

    /** Случается ли дело в этот день. Пустой набор — случается всегда. */
    fun on(days: Set<DayOfWeek>, date: LocalDate): Boolean =
        days.isEmpty() || date.dayOfWeek in days

    /** Две буквы дня: «Пн», «Вт». Ими же набран выбор в карточке. */
    fun short(day: DayOfWeek): String = when (day) {
        DayOfWeek.MONDAY -> "Пн"
        DayOfWeek.TUESDAY -> "Вт"
        DayOfWeek.WEDNESDAY -> "Ср"
        DayOfWeek.THURSDAY -> "Чт"
        DayOfWeek.FRIDAY -> "Пт"
        DayOfWeek.SATURDAY -> "Сб"
        DayOfWeek.SUNDAY -> "Вс"
    }

    /**
     * Набор словами — то, что стоит строкой в карточке и под названием дела.
     *
     * Будни и выходные названы словами, а не перечислены: «По будням» короче
     * пяти сокращений и читается тем же, чем человек их и задумал. Остальные
     * наборы перечисляются подряд, порядком недели.
     */
    fun title(days: Set<DayOfWeek>): String = when {
        days.isEmpty() || days.size == 7 -> "Каждый день"
        days == WORKDAYS -> "По будням"
        days == WEEKEND -> "По выходным"
        else -> week.filter { it in days }.joinToString(" ") { short(it) }
    }
}
