package app.askya.domain.account

/**
 * Сколько раз можно промахнуться — и что бывает потом.
 *
 * У пин-кода пять попыток, и после пятой он просто перестаёт приниматься до
 * тех пор, пока не войдут паролем. Ожидания здесь нет намеренно: четыре цифры
 * с ожиданием всё равно перебираются за ночь, а пять попыток из десяти тысяч
 * вариантов — это одна удача на две тысячи.
 *
 * У пароля и кода восстановления первые пять промахов бесплатны — пароль
 * набирают с опечатками, — а дальше каждый следующий удваивает паузу: полминуты,
 * минута, две… до часа. Совсем не запирается: хозяин, забывший раскладку,
 * должен иметь возможность войти, а подбирающему час на попытку — это годы.
 *
 * Правило — отдельными функциями без хранилища: на телефоне часы не
 * подкрутишь, а проверять его надо (`AttemptsTest`).
 */
object Attempts {

    const val PIN_TRIES = 5
    const val FREE_PASSWORD_TRIES = 5

    private const val FIRST_PAUSE_MS = 30_000L
    private const val LONGEST_PAUSE_MS = 60 * 60_000L

    /** Сколько попыток пин-кода осталось после стольких промахов. */
    fun pinLeft(misses: Int): Int = (PIN_TRIES - misses).coerceAtLeast(0)

    /** Сколько ждать после очередного промаха пароля. Ноль — не ждать. */
    fun pauseAfter(passwordMisses: Int): Long {
        val over = passwordMisses - FREE_PASSWORD_TRIES
        if (over < 0) return 0L
        // Сдвиг ограничен, чтобы не переполнить Long: на седьмом удвоении
        // пауза и так упирается в час.
        return (FIRST_PAUSE_MS shl over.coerceAtMost(8)).coerceAtMost(LONGEST_PAUSE_MS)
    }
}
