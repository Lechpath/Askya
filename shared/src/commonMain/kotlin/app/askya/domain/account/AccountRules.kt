package app.askya.domain.account

/**
 * Каким должен быть пароль и пин-код — одно правило на заведение аккаунта, на
 * смену пароля и на восстановление.
 *
 * **Пароль — от восьми знаков.** Пока он запирает Askya только на этом
 * устройстве, хватило бы и меньшего: файл с отпечатком лежит там, куда без
 * рута не достать. Но пароль — это ещё и ключ, которым будут закрыты записи,
 * уехавшие в облако, а там отпечаток перебирают уже не пальцем, а видеокартой:
 * шесть строчных букв сдаются за часы, восемь знаков вперемешку — за столетия.
 * Правило ставится сейчас, чтобы не заставлять менять пароль потом.
 *
 * **Пин-код — от четырёх до шести цифр.** Он для каждого дня и от подбора
 * защищён не длиной, а пятью попытками ([Attempts]); длиннее шести он
 * перестаёт быть быстрее пароля.
 */
object AccountRules {

    const val MIN_PASSWORD = 8
    const val MIN_PIN = 4
    const val MAX_PIN = 6
    const val MAX_NAME = 40

    /** Что не так с новым паролем; `null` — всё так. */
    fun passwordProblem(password: String, again: String): String? = when {
        password.length < MIN_PASSWORD -> "Пароль — не короче восьми знаков"
        password.isBlank() -> "Пароль из одних пробелов не годится"
        password != again -> "Пароли не совпадают"
        else -> null
    }

    /** Что не так с новым пин-кодом; `null` — всё так. */
    fun pinProblem(pin: String, again: String): String? = when {
        pin.any { it !in '0'..'9' } -> "В пин-коде только цифры"
        pin.length !in MIN_PIN..MAX_PIN -> "Пин-код — от четырёх до шести цифр"
        pin.toSet().size == 1 -> "Одна и та же цифра подряд угадывается первой"
        pin != again -> "Пин-коды не совпадают"
        else -> null
    }

    /** Что не так с именем; `null` — всё так. */
    fun nameProblem(name: String): String? = when {
        name.isBlank() -> "Нужно имя — его видно на входе"
        name.trim().length > MAX_NAME -> "Имя — не длиннее сорока знаков"
        else -> null
    }
}
