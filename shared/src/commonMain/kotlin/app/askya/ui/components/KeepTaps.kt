package app.askya.ui.components

import androidx.compose.foundation.gestures.detectTapGestures
import androidx.compose.ui.Modifier
import androidx.compose.ui.input.pointer.pointerInput

/**
 * Тап — и только тап: пальцем или мышью, без фокуса и без клавиш.
 *
 * Для затемнения позади окна («тап мимо — закрыть») и для самой карточки
 * ([keepTaps]). Раньше оба были `clickable`, и на телефоне разницы не видно:
 * экранная клавиатура клавиш не шлёт, а касание фокус не двигает. У
 * компьютера — и у телефона с настоящей клавиатурой — нажимаемое живёт ещё и
 * клавишами, и это ломало окна с полями:
 *
 * - пробел, набранный в поле, поле не забирает, и он доходил до затемнения —
 *   а пробел для нажимаемого то же, что щелчок. Карточка дела закрывалась на
 *   первом же пробеле в названии, и набранное пропадало;
 * - щелчок мышью по нажимаемому забирает фокус себе, и строка, в которой
 *   только что печатали, его теряла: щёлкнул по карточке мимо поля — и дальше
 *   набранное не попадало никуда, хотя строка по-прежнему подсвечена.
 *
 * Жест про фокус и клавиши не знает ничего. Ряби у него нет — но её тут и не
 * было: рябь во весь экран выглядела бы дико.
 */
fun Modifier.tapOnly(onTap: () -> Unit): Modifier =
    pointerInput(onTap) { detectTapGestures(onTap = { onTap() }) }

/**
 * Тап по самой карточке, который ничего не делает: карточка забирает его,
 * чтобы он не дошёл до затемнения позади и не закрыл окно. См. [tapOnly].
 */
fun Modifier.keepTaps(): Modifier = tapOnly(KeepTap)

/** Одна и та же пустышка на все карточки: иначе жест перезапускался бы. */
private val KeepTap: () -> Unit = {}
