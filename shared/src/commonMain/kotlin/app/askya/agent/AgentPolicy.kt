package app.askya.agent

/**
 * Все ограничения агента — в одном месте.
 *
 * Инструменты о них не знают и знать не должны: предел, разнесённый по
 * инструментам, где-нибудь да забудут, и тогда его нет нигде. Соблюдает их
 * [ToolTurn] — один на ход разговора.
 *
 * Значения по умолчанию — из архитектурного аудита (`AI_AGENT_ARCHITECTURE.md`,
 * §8): восемь вызовов за ход, три предложения, облако выключено.
 */
data class AgentPolicy(
    /** Сколько раз за ход модель может вызвать инструмент — любой, включая неизвестный. */
    val maxToolCalls: Int = 8,

    /** Сколько предложений может родиться за ход. */
    val maxProposals: Int = 3,

    /**
     * Сколько знаков может занять ответ инструмента, записанный в JSON, —
     * столько уйдёт модели. Меряется записью, а не числом строк: одна заметка
     * бывает длиннее двадцати дел.
     */
    val maxResultSize: Int = 16_000,

    /**
     * Можно ли агенту вообще предлагать изменения. Выключено — он только
     * читает, и инструменты-предложения даже не вызываются.
     */
    val allowProposals: Boolean = true,

    /**
     * Можно ли отдавать разговор модели в сети. По умолчанию нельзя: Askya
     * обещает, что записи с устройства не уходят (README, «Про сеть и
     * приватность»), и отступить от этого может только сам человек.
     */
    val allowCloud: Boolean = false,
) {
    init {
        require(maxToolCalls > 0) { "maxToolCalls должен быть больше нуля" }
        require(maxProposals >= 0) { "maxProposals не может быть меньше нуля" }
        require(maxResultSize > 0) { "maxResultSize должен быть больше нуля" }
    }

    /**
     * Можно ли работать с этим клиентом модели. [online] — уходит ли что-то с
     * устройства. Облачный клиент без разрешения не годится, локальный годится
     * всегда.
     */
    fun allowsClient(online: Boolean): Boolean = !online || allowCloud
}
