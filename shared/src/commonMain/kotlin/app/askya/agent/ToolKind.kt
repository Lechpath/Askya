package app.askya.agent

/**
 * Два рода инструментов агента — и третьего нет.
 *
 * Записи среди них нет намеренно: инструмент не пишет никогда. Он либо читает
 * ([READ]), либо собирает предложение ([PROPOSE]), которое человек потом
 * подтвердит или отклонит. Применяет подтверждённое отдельный механизм, до
 * которого у модели руки не дотягиваются.
 *
 * Род у инструмента не объявляется словами, а следует из того, какой он:
 * [ReadTool] или [ProposeTool] (см. [kind]). Иначе инструмент мог бы назваться
 * читающим, а на деле собирать предложения.
 */
enum class ToolKind {
    READ,
    PROPOSE,
}
